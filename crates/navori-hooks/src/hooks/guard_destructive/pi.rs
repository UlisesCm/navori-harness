//! Rule 6c of guard-destructive.sh: the arm that exists only in a Pi copy (spec 0048 D4/D15).
//! Control-plane writes and `pi --no-extensions` block; shared `deny` rules block and the first
//! matching shared `ask` rule is remembered for the exit trap.

use regex::Regex;

use super::tr;
use crate::shell::Locale;

const CONTROL_PLANE: &str = r#"\.pi/(navori(\.json|/[^[:space:];&|<>"']*)?|extensions(/[^[:space:];&|<>"']*)?|settings\.json)"#;
const CONTROL_PLANE_END: &str = r#"([[:space:]"';&|)<>]|$)"#;
const CONTROL_PLANE_MSG: &str = "shell write to the Pi control plane (.pi/navori, .pi/extensions, .pi/settings.json, .pi/navori.json) — these files decide whether the guards run. Navori's own are regenerated by 'navori render --apply' (or 'navori sync'); any other change is for the user to make outside the agent";
const NO_EXTENSIONS_MSG: &str = "pi --no-extensions starts an agent without Navori's guards (no extension, no bridge, no hooks)";

/// Compiled 6c expressions for one locale. Every control-plane check is case-insensitive.
pub(super) struct Patterns {
    segment: Regex,
    verbs: Regex,
    sed: Regex,
    git: Regex,
    interpreter: Regex,
    redirect: Regex,
    no_extensions: Regex,
}

impl Patterns {
    pub(super) fn new(locale: Locale) -> Result<Self, regex::Error> {
        let re = |pattern: &str| locale.ere(pattern);
        Ok(Self {
            segment: re(&format!("(?i){CONTROL_PLANE}{CONTROL_PLANE_END}"))?,
            verbs: re(
                r#"(?i)(^|[[:space:]"'])(rm|rmdir|unlink|mv|cp|ln|dd|install|truncate|chmod|chown|rsync|tee|touch|mkdir)[[:space:]]"#,
            )?,
            sed: re(
                r#"(?i)(^|[[:space:]"'])sed[[:space:]]+(-[a-zA-Z]*i[a-zA-Z]*[^[:space:]]*|--in-place)([[:space:]]|=)"#,
            )?,
            git: re(r"(?i)^git[[:space:]]+(.*[[:space:]])?(checkout|restore)[[:space:]]")?,
            interpreter: re(
                r#"(?i)(^|[[:space:]"'])(python[0-9.]*|node(js)?|deno|bun|perl|ruby|php|osascript)[[:space:]]+(.*[[:space:]])?(-[a-zA-Z]*[cepir][a-zA-Z]*|--eval|--print)([[:space:]=]|$)"#,
            )?,
            redirect: re(&format!(
                r#"(?i)>[>|]?[[:space:]]*["']?([^[:space:];&|<>]*/)?{CONTROL_PLANE}{CONTROL_PLANE_END}"#
            ))?,
            no_extensions: re(
                r#"(^|[[:space:]"'/])pi[[:space:]]+(.*[[:space:]])?(--no-extensions|-ne)([[:space:]=]|$)"#,
            )?,
        })
    }
}

/// What the Pi arm decided.
pub(super) enum Verdict {
    /// `block <message> <reason> [route]`.
    Block {
        message: String,
        reason: &'static str,
        route: Option<&'static str>,
    },
    /// No block; `navori_pi_ask` holds the first matching `ask` prefix, if any.
    Pass(Option<String>),
}

/// Run 6c over `segments` (one per line) and `scan`. `rules` is `nv_pi_rules` verbatim.
pub(super) fn evaluate(
    segments: &[String],
    scan_lines: &[String],
    rules: &str,
    patterns: &Patterns,
) -> Verdict {
    let write = segments
        .iter()
        .filter(|segment| patterns.segment.is_match(segment))
        .any(|segment| {
            patterns.verbs.is_match(segment)
                || patterns.sed.is_match(segment)
                || patterns.git.is_match(segment)
                || patterns.interpreter.is_match(segment)
        });
    if write
        || scan_lines
            .iter()
            .any(|line| patterns.redirect.is_match(line))
    {
        return Verdict::Block {
            message: CONTROL_PLANE_MSG.to_owned(),
            reason: "managed-rewrite",
            route: Some("navori render --apply"),
        };
    }
    if segments
        .iter()
        .any(|segment| patterns.no_extensions.is_match(segment))
    {
        return Verdict::Block {
            message: NO_EXTENSIONS_MSG.to_owned(),
            reason: "unspecified",
            route: None,
        };
    }
    if rules == "-" {
        return Verdict::Pass(None);
    }
    // `read -r` over a here-string: every line of the rules, the last without its newline.
    let prefixes = |kind: &'static str| {
        rules
            .split('\n')
            .filter_map(move |rule| rule.strip_prefix(kind))
    };
    let mut ask = None;
    for segment in segments {
        let segment = normalize(segment);
        let segment = segment.strip_prefix(' ').unwrap_or(&segment);
        let segment = segment.strip_suffix(' ').unwrap_or(segment);
        if segment.is_empty() {
            continue;
        }
        let matches = |prefix: &str| {
            segment == prefix
                || segment
                    .strip_prefix(prefix)
                    .is_some_and(|rest| rest.starts_with(' '))
        };
        if let Some(prefix) = prefixes("deny ").find(|prefix| matches(prefix)) {
            return Verdict::Block {
                message: format!(
                    "shared permission deny rule '{prefix}' (the same rule that denies it in Claude and Codex)"
                ),
                reason: "unspecified",
                route: None,
            };
        }
        if ask.is_none() {
            ask = prefixes("ask ")
                .find(|prefix| matches(prefix))
                .map(str::to_owned);
        }
    }
    Verdict::Pass(ask)
}

/// `tr -d "'\"" | tr -s '[:blank:]' ' '` for one segment.
fn normalize(segment: &str) -> String {
    let mut out = String::with_capacity(segment.len());
    for c in segment.chars().filter(|c| !matches!(c, '\'' | '"')) {
        if tr::blank(c) {
            if !out.ends_with(' ') {
                out.push(' ');
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// The exit trap's answer to a remembered `ask` rule: stdout and the audit reason. The prefix
/// loses quotes, backslashes and control characters (`tr -d '"\\[:cntrl:]'`).
#[must_use]
pub fn ask_answer(prefix: &str, locale: Locale) -> (String, String) {
    let text: String = prefix
        .chars()
        .filter(|c| !matches!(c, '"' | '\\') && !tr::cntrl(locale, *c))
        .collect();
    let stdout = format!(
        "{{\"hookSpecificOutput\":{{\"hookEventName\":\"PreToolUse\",\"permissionDecision\":\"ask\",\"permissionDecisionReason\":\"[navori] shared permission ask rule {text}: this command needs your confirmation before it runs (the same rule asks in Claude and Codex).\"}}}}\n"
    );
    (stdout, format!("shared permission ask rule '{text}'"))
}
