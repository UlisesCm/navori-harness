/// The header navori seeds a fresh `.codex/config.toml` with.
const CODEX_CONFIG_HEADER: &str = "# Codex project config generated by navori.\n";
/// The header navori seeds a fresh `.codex/rules/navori.rules` with.
const CODEX_RULES_HEADER: &str = "# Codex terminal permission rules generated by navori.\n";

/// `minCodexVersion()`: static, checked against the TS by `codex_engine_parity`.
pub const MIN_CODEX_VERSION: &str = "0.162.1";

/// What the Codex engine plans.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CodexEnginePlan {
    /// Files to write, in the order `finalize` leaves them.
    pub pending: Vec<PendingWrite>,
    /// Orphans to delete.
    pub removals: Vec<PendingRemoval>,
    /// Files kept.
    pub skipped: Vec<SkippedFile>,
    /// `(relPath, overwrittenKeys)` of markerless destinations adopted by name.
    pub collisions: Vec<(String, Vec<String>)>,
    /// Warnings up to `commit` (which appends the collision notes).
    pub warnings: Vec<String>,
}

/// What the Codex engine reads besides the repo.
pub struct CodexEngineInput<'a> {
    /// The configured config.
    pub config: &'a JsValue,
    /// The repo root (also the render's cwd).
    pub repo_root: &'a Path,
    /// `setMarkerFloorVersion`.
    pub ambient_floor: Option<&'a str>,
    /// The ported hooks (`loadNativeHooks()`).
    pub native_manifest: &'a BTreeMap<String, Hook>,
    /// The model catalog, `defaultCodexCatalogPath()` in a real render.
    pub catalog: Option<std::path::PathBuf>,
}

fn get<'a>(value: &'a JsValue, key: &str) -> Option<&'a JsValue> {
    match value {
        JsValue::Object(object) => object.get(key),
        _ => None,
    }
}

fn text(value: Option<&JsValue>) -> Option<String> {
    match value? {
        JsValue::String(text) => text.to_rust(),
        _ => None,
    }
}

fn strings(value: Option<&JsValue>) -> Vec<String> {
    match value {
        Some(JsValue::Array(items)) => items.iter().filter_map(|i| text(Some(i))).collect(),
        _ => Vec::new(),
    }
}

fn declares_hooks(plugin: &LoadedPlugin) -> bool {
    match get(&plugin.manifest, "hooks") {
        None | Some(JsValue::Undefined) => false,
        Some(JsValue::Array(items)) => !items.is_empty(),
        Some(_) => true,
    }
}

/// The inputs the plan, the observations and the render share.
struct Ctx<'a> {
    view: &'a dyn RepoView,
    cwd: &'a Path,
    config: JsValue,
    lang: Lang,
    floor: Option<&'a str>,
    plan: HarnessPlan,
    enabled: Vec<LoadedPlugin>,
    disabled: Vec<LoadedPlugin>,
    installed: Vec<String>,
    catalog: Option<std::path::PathBuf>,
    preset_loaded: bool,
    warnings: Vec<String>,
}

fn prepare<'a>(
    view: &'a dyn RepoView,
    input: &CodexEngineInput<'a>,
) -> Result<Ctx<'a>, CodexDelegate> {
    let config = effective_config(input.config);
    let lang = Lang::resolve(text(get(&config, "language")).as_deref());
    let plugins_config = get(&config, "plugins").cloned();
    let enabled = load_enabled_plugins(plugins_config.as_ref()).map_err(|_| CodexDelegate)?;
    let disabled = load_disabled_plugins(plugins_config.as_ref()).map_err(|_| CodexDelegate)?;
    if enabled
        .loaded
        .iter()
        .chain(&disabled.loaded)
        .any(declares_hooks)
    {
        return Err(CodexDelegate);
    }
    if !strings(get(&config, "project").and_then(|p| get(p, "localSkills"))).is_empty() {
        return Err(CodexDelegate);
    }
    let mut warnings: Vec<String> = enabled
        .missing
        .iter()
        .map(|id| i18n::plugin_load_failed_codex(lang, id, "unknown plugin id"))
        .collect();
    // `loadActivePreset`.
    let preset_id = text(get(&config, "preset"));
    let preset: Option<LoadedPreset> = match preset_id.as_deref() {
        None | Some("" | "custom") => None,
        Some(id) => {
            let preset = load_preset(id, input.repo_root).map_err(|_| CodexDelegate)?;
            match &preset {
                None => warnings.push(i18n::preset_not_found_codex(lang, id)),
                Some(loaded) => warnings.extend(loaded.dropped_libraries.iter().map(|lib| {
                    format!(
                        "preset '{}' declares library '{lib}', unknown to this CLI's registry; skipped.",
                        text(get(&loaded.def, "id")).unwrap_or_default()
                    )
                })),
            }
            preset
        }
    };
    let preset_loaded = match preset_id.as_deref() {
        None | Some("" | "custom") => true,
        Some(id) => preset
            .as_ref()
            .is_some_and(|p| text(get(&p.def, "id")).as_deref() == Some(id)),
    };
    let plan = resolve_harness_plan(&config, preset.as_ref(), false, Some("codex"));
    let catalog = input.catalog.clone();
    let profiles =
        project_codex_profiles(input.repo_root, &config, catalog.as_deref(), &plan.agents)
            .map_err(|_| CodexDelegate)?;
    for diagnostic in profiles.iter().flat_map(|row| &row.diagnostics) {
        if !warnings.contains(diagnostic) {
            warnings.push(diagnostic.clone());
        }
    }
    let project = get(&config, "project");
    let mut libraries = strings(project.and_then(|p| get(p, "libraries")));
    libraries.extend(strings(project.and_then(|p| get(p, "extraLibraries"))));
    for (id, removed, successors) in unknown_libraries(&libraries) {
        warnings.push(if removed {
            i18n::library_removed_from_registry(lang, &id, successors)
        } else {
            i18n::library_unknown_in_registry(lang, &id)
        });
    }
    // A plugin skill aimed at an agent Codex neither renders nor embodies (#277).
    for plugin in &enabled.loaded {
        let plugin_id = plugin.manifest_id();
        for skill in &plugin.skill_assets {
            let Some(target) = skill.inject_into.as_deref() else {
                continue;
            };
            let Some(agent) = target
                .strip_prefix(".claude/agents/")
                .and_then(|rest| rest.strip_suffix(".md"))
                .filter(|id| {
                    !id.is_empty()
                        && id
                            .bytes()
                            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
                })
            else {
                continue;
            };
            if agent == "orchestrator" || plan.agents.iter().any(|a| a.id == agent) {
                continue;
            }
            warnings.push(i18n::plugin_skill_not_injected(
                lang, &skill.id, &plugin_id, target,
            ));
        }
    }
    let installed = codex_installed_scripts(&config, &enabled.loaded).ok_or(CodexDelegate)?;
    Ok(Ctx {
        view,
        cwd: input.repo_root,
        config,
        lang,
        floor: input.ambient_floor,
        plan,
        enabled: enabled.loaded,
        disabled: disabled.loaded,
        installed,
        catalog,
        preset_loaded,
        warnings,
    })
}

/// One retained placement request.
enum Request {
    /// An asset rendered with `renderManagedFile`.
    Asset {
        rel: String,
        asset: String,
        managed_id: String,
        source: String,
        extra_vars: Option<BTreeMap<String, String>>,
        chmod_exec: bool,
        plugin: bool,
        /// The guard's `navoriOwnedPaths`, filled from the sealed inventory.
        guard: bool,
    },
    /// A body injected as navori's block.
    Body {
        rel: String,
        managed_id: String,
        body: String,
        style: CommentStyle,
        header: &'static str,
        trailer: &'static str,
    },
    /// Already collected (agents, skills and `AGENTS.md`, rendered at placement time).
    Collected {
        rel: String,
        managed_id: String,
        collected: Collected,
    },
}

impl Request {
    fn destination(&self) -> (&str, &str) {
        match self {
            Self::Asset {
                rel, managed_id, ..
            }
            | Self::Body {
                rel, managed_id, ..
            }
            | Self::Collected {
                rel, managed_id, ..
            } => (rel, managed_id),
        }
    }
}

/// Every Codex placement, in `retainPlan` order, plus the warnings it pushes to the sink.
fn requests(ctx: &Ctx<'_>) -> Result<(Vec<Request>, Vec<String>), CodexDelegate> {
    let mut sink = Vec::new();
    let mut out = Vec::new();
    let agents = collect_codex_agents(
        ctx.view,
        ctx.cwd,
        &ctx.plan.agents,
        &ctx.config,
        &ctx.enabled,
        ctx.catalog.as_deref(),
        ctx.floor,
        ctx.lang,
    )?;
    sink.extend(agents.warnings);
    let placed: Vec<&str> = agents.catalog.iter().map(|(id, _)| id.as_str()).collect();
    let mut files = agents.files.into_iter();
    for agent in &ctx.plan.agents {
        if !placed.contains(&agent.id.as_str()) {
            continue;
        }
        out.push(Request::Collected {
            rel: format!(".codex/agents/{}.toml", agent.id),
            managed_id: format!("{}-codex-base", agent.id),
            collected: files.next().ok_or(CodexDelegate)?,
        });
    }
    let skills =
        collect_codex_skills(ctx.view, &ctx.plan.skills, &ctx.config, ctx.floor, ctx.lang)?;
    for (skill, collected) in ctx.plan.skills.iter().zip(skills.files) {
        out.push(Request::Collected {
            rel: format!(".agents/skills/{}/SKILL.md", skill.id),
            managed_id: skill.managed_id.clone(),
            collected,
        });
    }
    for hook in &ctx.plan.hooks {
        let rel = format!(".codex/hooks/{}.sh", hook.id);
        if !ctx.installed.contains(&rel) {
            continue;
        }
        let extra = codex_hook_extra_vars(&hook.id, &ctx.config)?;
        out.push(Request::Asset {
            rel,
            asset: asset_text(&hook.asset).map_err(|_| CodexDelegate)?,
            managed_id: hook.managed_id.clone(),
            source: CORE_SOURCE_ID.to_owned(),
            extra_vars: (!extra.is_empty()).then_some(extra),
            chmod_exec: true,
            plugin: false,
            guard: hook.id == "guard-destructive",
        });
    }

    // `extraFiles`.
    let body = agents_md_body(
        &ctx.config,
        ctx.cwd,
        &ctx.enabled,
        &agents.catalog,
        ctx.floor,
        ctx.lang,
    )?;
    let agents_md_bytes = body.len() as u64;
    out.push(Request::Collected {
        rel: "AGENTS.md".to_owned(),
        managed_id: "navori-agents".to_owned(),
        collected: collect_agents_md(ctx.view, &body, ctx.floor, ctx.lang)?,
    });
    out.push(Request::Collected {
        rel: ".codex/orchestrator.md".to_owned(),
        managed_id: "orchestrator-codex-base".to_owned(),
        collected: collect_orchestrator(ctx.view, &ctx.config, ctx.floor, ctx.lang)?,
    });
    let permissions =
        collect_shell_permission_rules(&ctx.config, &ctx.enabled).map_err(|_| CodexDelegate)?;
    let rules = build_codex_rules(&permissions.ask, &permissions.deny).ok_or(CodexDelegate)?;
    let not_bash = rules
        .dropped
        .iter()
        .filter(|(_, reason)| *reason == DropReason::NotBash)
        .count();
    let wildcard = rules
        .dropped
        .iter()
        .filter(|(_, reason)| *reason == DropReason::InnerWildcard)
        .count();
    if !rules.dropped.is_empty() || !rules.narrowed.is_empty() {
        sink.push(i18n::codex_rules_summary(
            ctx.lang,
            not_bash,
            wildcard,
            rules.narrowed.len(),
        ));
    }
    let codex_config = build_codex_config_toml(
        &ctx.config,
        &ctx.enabled,
        "",
        agents_md_bytes,
        Some(ctx.cwd),
        ctx.catalog.as_deref(),
    )
    .ok_or(CodexDelegate)?;
    sink.extend(codex_config.warnings);
    out.push(Request::Body {
        rel: ".codex/config.toml".to_owned(),
        managed_id: "codex-config-base".to_owned(),
        body: codex_config.body,
        style: CommentStyle::Shell,
        header: CODEX_CONFIG_HEADER,
        trailer: "",
    });
    out.push(Request::Body {
        rel: ".codex/rules/navori.rules".to_owned(),
        managed_id: "codex-rules-base".to_owned(),
        body: rules.body,
        style: CommentStyle::Shell,
        header: CODEX_RULES_HEADER,
        trailer: "",
    });
    let collisions = plugin_script_collisions(&ctx.enabled);
    for plugin in &ctx.enabled {
        for script in plugin_script_placements(plugin, ScriptEngine::Codex) {
            if collisions.contains(&script.script.dest)
                || !ctx.installed.contains(&script.dest_rel_path)
            {
                continue;
            }
            out.push(Request::Asset {
                rel: script.dest_rel_path.clone(),
                asset: script.template().ok_or(CodexDelegate)?.to_owned(),
                managed_id: script.managed_id.clone(),
                source: script.source.clone(),
                extra_vars: Some(BTreeMap::new()),
                chmod_exec: script.script.exec,
                plugin: true,
                guard: false,
            });
        }
    }
    for id in &skills.manual_only {
        let collected =
            collect_openai_policies(ctx.view, std::slice::from_ref(id), ctx.floor, ctx.lang)?;
        out.push(Request::Collected {
            rel: format!(".agents/skills/{id}/agents/openai.yaml"),
            managed_id: format!("{id}-openai-policy"),
            collected: collected.into_iter().next().ok_or(CodexDelegate)?,
        });
    }
    Ok((out, sink))
}

/// The destinations this engine observes in the shared owned-path inventory: every placement and
/// every extension target `retainOverlay` keeps (selected, or on disk).
fn observations(ctx: &Ctx<'_>, requests: &[Request]) -> Vec<(String, String)> {
    let mut out: Vec<(String, String)> = requests
        .iter()
        .map(|r| {
            let (rel, id) = r.destination();
            (rel.to_owned(), id.to_owned())
        })
        .collect();
    let mut overlays: Vec<(String, String)> = Vec::new();
    for plugin in ctx.enabled.iter().chain(&ctx.disabled) {
        for skill in &plugin.skill_assets {
            if let Some(id) = skill.inject_into.as_deref().and_then(skill_inject_target) {
                overlays.push((format!(".agents/skills/{id}/SKILL.md"), skill.id.clone()));
            }
        }
        for extension in &plugin.hook_extension_assets {
            if let Some(target) = codex_hook_extension_target(&extension.target) {
                overlays.push((target, extension.id.clone()));
            }
        }
    }
    for (_, _, entries) in RETIRED_PLUGIN_SUB_BLOCKS {
        for (id, target) in *entries {
            if let Some(skill) = skill_inject_target(target) {
                overlays.push((format!(".agents/skills/{skill}/SKILL.md"), (*id).to_owned()));
            }
        }
    }
    for (target, id) in overlays {
        // A selected target is sealed by its placement already; only one on disk adds to it.
        if ctx.view.lexists(&target) {
            out.push((target, id));
        }
    }
    out
}

/// What the Codex engine observes in the shared inventory, for the other engines' guards.
///
/// # Errors
/// [`CodexDelegate`] where the engine delegates.
pub fn codex_observed(
    view: &dyn RepoView,
    input: &CodexEngineInput<'_>,
) -> Result<Vec<(String, String)>, CodexDelegate> {
    let ctx = prepare(view, input)?;
    let (requests, _) = requests(&ctx)?;
    Ok(observations(&ctx, &requests))
}

/// The sealed inventory over `observed`.
///
/// # Errors
/// [`CodexDelegate`] where `observe` throws.
pub fn seal_observed(
    view: &dyn RepoView,
    observed: &[(String, String)],
) -> Result<String, CodexDelegate> {
    let mut owned = OwnedPaths::default();
    for (rel, id) in observed {
        owned
            .observe(view, rel, id, Classify::Marker)
            .map_err(|_| CodexDelegate)?;
    }
    Ok(owned.seal())
}

/// A plugin-sourced asset whose destination navori does not own untouched (`collectRequest`'s
/// plugin branch): `newer` is kept as a downgrade, anything else delegates.
fn plugin_guard(
    view: &dyn RepoView,
    rel: &str,
    managed_id: &str,
    lang: Lang,
) -> Result<Option<SkippedFile>, CodexDelegate> {
    let Some(existing) = read_if_exists(view, rel).map_err(|_| CodexDelegate)? else {
        return Ok(None);
    };
    match crate::render::removable::navori_authorship(view, rel, Some(managed_id), true) {
        Authorship::Ours => Ok(None),
        Authorship::Newer => Ok(Some(SkippedFile {
            rel_path: rel.to_owned(),
            reason: i18n::block_from_newer_navori(
                lang,
                read_marker_attrs(&existing, managed_id, CommentStyle::Shell)
                    .and_then(|attrs| attrs.existing_version)
                    .as_deref(),
            ),
            status: Some(InjectStatus::DowngradeSkipped),
            resolution: None,
            markerless_resolution: None,
            chmod_exec: false,
        })),
        _ => Err(CodexDelegate),
    }
}

/// `scriptManagedId`: the id of the first shell opening marker.
fn script_managed_id(content: &str) -> String {
    content
        .split('\n')
        .find_map(|line| {
            let rest = line.strip_prefix("# navori:managed start id=\"")?;
            rest.find('"').map(|end| rest[..end].to_owned())
        })
        .unwrap_or_default()
}

/// `prepareCodexEngine(cwd, config, { dryRun })` then `finalize()`, with `owned_paths` the
/// sealed inventory of every engine of the target.
///
/// # Errors
/// [`CodexDelegate`] where the TS throws or Rust does not model the render.
pub fn plan_codex_engine(
    view: &dyn RepoView,
    input: &CodexEngineInput<'_>,
    owned_paths: &str,
) -> Result<CodexEnginePlan, CodexDelegate> {
    let ctx = prepare(view, input)?;
    let (requests, sink) = requests(&ctx)?;
    let mut plan = CodexEnginePlan {
        warnings: ctx.warnings.clone(),
        ..CodexEnginePlan::default()
    };
    let mut render_vars: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    for request in requests {
        let collected = match request {
            Request::Collected { collected, .. } => collected,
            Request::Body {
                rel,
                managed_id,
                body,
                style,
                header,
                trailer,
            } => {
                let request = BodyRequest {
                    header,
                    trailer,
                    ..BodyRequest::new(&rel, &managed_id, &body, style)
                };
                collect_body(view, &request, ctx.floor, ctx.lang).map_err(|_| CodexDelegate)?
            }
            Request::Asset {
                rel,
                asset,
                managed_id,
                source,
                extra_vars,
                chmod_exec,
                plugin,
                guard,
            } => {
                let extra_vars = if guard {
                    Some(BTreeMap::from([(
                        "navoriOwnedPaths".to_owned(),
                        owned_paths.to_owned(),
                    )]))
                } else {
                    extra_vars
                };
                if let Some(vars) = &extra_vars {
                    render_vars.insert(rel.clone(), vars.clone());
                }
                if plugin && let Some(skip) = plugin_guard(view, &rel, &managed_id, ctx.lang)? {
                    plan.skipped.push(skip);
                    continue;
                }
                let existing = read_if_exists(view, &rel).map_err(|_| CodexDelegate)?;
                let input = RenderManagedFileInput {
                    asset: &asset,
                    style: CommentStyle::Shell,
                    existing: existing.as_deref(),
                    managed_id: &managed_id,
                    source: &source,
                    version: STAMP_VERSION,
                    config: &ctx.config,
                    extra_vars: extra_vars.unwrap_or_default(),
                    transform: None,
                    engine: Some("codex"),
                    force_overwrite: false,
                    ambient_floor: ctx.floor,
                };
                let mut collected = collect_managed(view, &rel, &input, chmod_exec, ctx.lang)
                    .map_err(|_| CodexDelegate)?;
                if plugin {
                    collected.collision = None;
                }
                collected
            }
        };
        if let (Some(keys), Some(write)) = (&collected.collision, &collected.write) {
            plan.collisions.push((write.rel_path.clone(), keys.clone()));
        }
        plan.pending.extend(collected.write);
        plan.skipped.extend(collected.skip);
    }
    let orphans = if ctx.preset_loaded {
        collect_codex_orphans(
            view,
            ctx.cwd,
            &ctx.plan,
            &ctx.installed,
            &ctx.config,
            &ctx.enabled,
        )?
    } else {
        CodexOrphans::default()
    };
    plan.removals = orphans.removals;

    // `finalize`.
    plan.warnings.extend(sink);
    for write in &plan.pending {
        if !write.rel_path.starts_with(".codex/scripts/") || write.status != InjectStatus::Updated {
            continue;
        }
        let Some(old) = read_if_exists(view, &write.rel_path).map_err(|_| CodexDelegate)? else {
            continue;
        };
        let old_body = extract_managed_content(&old, &script_managed_id(&old), CommentStyle::Shell);
        let new_body = extract_managed_content(
            &write.content,
            &script_managed_id(&write.content),
            CommentStyle::Shell,
        );
        if let (Some(old_body), Some(new_body)) = (old_body, new_body)
            && old_body != new_body
        {
            plan.warnings
                .push(i18n::codex_plugin_script_changed(ctx.lang, &write.rel_path));
        }
    }
    if plan
        .skipped
        .iter()
        .any(|s| s.rel_path == ".codex/config.toml")
        && let Some(config_text) =
            read_if_exists(view, ".codex/config.toml").map_err(|_| CodexDelegate)?
    {
        // No disabled plugin declares `hooks` (that delegates), so only retired scripts remain.
        for name in retired_script_basenames() {
            let path = format!(".codex/scripts/{name}");
            if config_text.contains(&path) {
                plan.warnings
                    .push(i18n::codex_residual_plugin_hook(ctx.lang, &path));
            }
        }
    }
    for kept in &orphans.kept {
        plan.warnings.push(i18n::kept_orphan_codex(
            ctx.lang,
            &kept.rel_path,
            kept.reason.as_str(),
        ));
    }
    plan.warnings.extend(apply_codex_skill_sub_blocks(
        view,
        &mut plan.pending,
        &ctx.enabled,
        &ctx.disabled,
        &ctx.config,
        ctx.floor,
        ctx.lang,
    )?);
    let sub_ctx = SubBlockCtx {
        view,
        config: &ctx.config,
        lang: ctx.lang,
        ambient_floor: ctx.floor,
    };
    let mut extension_out = SubBlocks::default();
    for plugin in &ctx.enabled {
        for extension in &plugin.hook_extension_assets {
            let Some(target) = codex_hook_extension_target(&extension.target) else {
                continue;
            };
            apply_hook_extension(
                &sub_ctx,
                plugin,
                extension,
                &target,
                &mut plan.pending,
                &mut extension_out,
            )
            .map_err(|_| CodexDelegate)?;
        }
    }
    for plugin in &ctx.disabled {
        for extension in &plugin.hook_extension_assets {
            let Some(target) = codex_hook_extension_target(&extension.target) else {
                continue;
            };
            remove_hook_extension(&sub_ctx, extension, &target, &mut plan.pending)
                .map_err(|_| CodexDelegate)?;
        }
    }
    plan.skipped.extend(extension_out.skipped);
    let hooks: Vec<_> = ctx
        .plan
        .hooks
        .iter()
        .filter(|hook| {
            ctx.installed
                .contains(&format!(".codex/hooks/{}.sh", hook.id))
        })
        .cloned()
        .collect();
    finalize_native_hooks(
        &NativeHooksInput {
            view,
            config: &ctx.config,
            hooks: &hooks,
            plugins: &ctx.enabled,
            manifest: input.native_manifest,
            ambient_floor: ctx.floor,
            owned_paths: Some(owned_paths),
            engine: NativeEngine::Codex,
            render_vars: Some(&render_vars),
        },
        &mut plan.pending,
    )
    .map_err(|_| CodexDelegate)?;
    Ok(plan)
}
