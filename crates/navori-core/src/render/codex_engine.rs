//! hooks, then `extraFiles`), the orphan scans, the finalize steps (skill sub-blocks, hook
//! extensions, native hooks) and the warnings, in the TS order.
//!
//! Not modeled, and delegated: workspaces and the `root` scope, `project.localSkills`, a plugin
//! that declares `hooks` (enabled or disabled), a plugin script on disk navori does not own
//! untouched, and the cases each piece module names.

