#!/usr/bin/env bash
#
# PreToolUse(apply_patch | spawn_agent) guard, CODEX ONLY (spec 0041 D5/D13,
# R6/R7/R8/R17/R31). Claude restricts a role with the agent's `tools:`
# allowlist; a Codex agent has no such field, so this hook is the mechanical
# equivalent. It never renders into `.claude/` (`HOOK_ENGINES`).
#
# TWO BRANCHES, both keyed on the top-level `agent_type`, which the host adds
# only when the hook fires inside a subagent. Absent or empty: the main thread,
# never blocked (R8).
#   1. spawn_agent (V1 name, or any V2 name ending in `spawn_agent`): a subagent
#      may not dispatch another one, whatever its role (R17/R31, depth 1). The
#      caller is named in the message.
#   2. apply_patch: `implementer` and `scribe` pass untouched (the first writes
#      production code, the second the Markdown the implementer must not). Any
#      other role may patch only the prefixes `RosterAgent.writes` grants it, or
#      an OS temp file. `default` and unknown roles get the common set
#      (fail-closed). Every path of a multi-file patch is checked.
#
# PATH CHECK. Each path is resolved against the payload `cwd`, normalized
# lexically (`..` cannot climb out unnoticed), then resolved physically so a
# symlink that leaves the repo is judged by where it lands. Inside the repo the
# role's prefixes decide, compared by path COMPONENT, not by text. Outside the
# repo only an OS temp root passes.
#
# FAIL-OPEN WITHOUT jq AND node (accepted, spec 0041): the sed fallback of
# `payload_field` cannot tell the top-level `agent_type` from
# `tool_input.agent_type`, so a main-thread spawn would be read as a subagent
# call and wrongly denied. With neither tool installed the hook lets the call
# through; upgrade trigger: ship a parser that reads only top-level keys.
#
# WHAT IT IS NOT. Bash writes keep the same containment as Claude (none by
# path); this guards the structured `apply_patch` channel only. Best-effort
# against inertia, not a sandbox against a deliberate adversary. If the payload
# cannot be read reliably it lets the call through.
#
# The per-role prefixes are NOT written here: they come from
# `RosterAgent.writes`, compiled by `buildRolePolicyShell` at render time.
#
# The managed block below is regenerated by `navori render` and must NOT be
# edited by hand.
# Blocking classification (#1117):
#   - a role touching what its contract forbids: hard — role containment; the message names the route.
set -euo pipefail

# Shared hook boilerplate — inlined into each hook at render time (see the
# include directive in the source scripts + lib/render/hook-includes.ts). Single source
# of truth for the sibling gate scripts; DO NOT copy this body back into a hook
# by hand (that is the drift #225/#261 removed).
#
# PreToolUse(Bash) passes the tool input on stdin. Read one field out of it
# WITHOUT hard-depending on jq (NOT preinstalled on macOS): try jq, then node
# (Claude Code's own runtime), then a best-effort sed unwrap on the leaf key.
# Nothing extracted → empty output, and each caller decides what that means (the
# gate scripts scan defensively; guard-destructive waves the command through).
#
# $1 is a dotted path written HERE, never user input — the payload is the data.
# Generic on purpose: `.cwd` feeds the worktree resolver of #454 through the
# SAME hardened cascade instead of a second copy of it.
#
# The sed fallback reads a JSON string through its first unescaped quote. JSON
# object member order is not a host contract: `command` can precede `cwd`, so a
# greedy capture to the last quote would swallow the rest of the payload when
# neither jq nor node is available.
# `${payload-$(cat)}` (unset test, not `:-`) rather than an unconditional
# `payload=$(cat)`: a caller that already captured stdin itself (spec 0035 —
# `managed-drift-watch.sh` needs the audit recorder's session_id/cwd even on
# tool names this hook does not otherwise read) keeps that value, empty or
# not, instead of this partial re-reading an already-drained pipe and
# clobbering it with "".
payload=${payload-$(cat)}
payload_field() {
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$payload" | jq -r ".$1 // empty" 2>/dev/null && return 0
  fi
  if command -v node >/dev/null 2>&1; then
    printf '%s' "$payload" | node -e 'let s="";const p=process.argv[1].split(".");process.stdin.on("data",c=>s+=c).on("end",()=>{try{let v=JSON.parse(s);for(const k of p)v=v?.[k];process.stdout.write(String(v??""))}catch{}})' "$1" 2>/dev/null && return 0
  fi
  printf '%s' "$payload" | sed -nE "s/.*\"${1##*.}\"[[:space:]]*:[[:space:]]*\"(([^\"\\]|\\.)*)\".*/\\1/p"
}
extract_cmd() {
  payload_field tool_input.command
}
