navori_root=$(cd -P "${nv_project_dir:-$navori_cwd}" 2>/dev/null && pwd -P) || navori_root=""
if [ -z "$navori_root" ]; then
  navori_audit_verdict="skip"
  navori_audit_reason="raíz del repo ilegible"
  exit 0
fi

navori_allowed=$(nv_role_prefixes "$navori_role")
navori_allowed_list=$(printf '%s' "$navori_allowed" | tr '\n' ' ')
navori_allowed_list=${navori_allowed_list% }

while IFS= read -r navori_path; do
  [ -n "$navori_path" ] || continue
  case "$navori_path" in
    /*) navori_abs=$(nv_normalize "$navori_path") ;;
    *) navori_abs=$(nv_normalize "$navori_cwd/$navori_path") ;;
  esac
  navori_real=$(nv_realpath "$navori_abs")
  if [ -z "$navori_real" ]; then
    block "$navori_role no escribe '$navori_path' (ruta no resoluble; permitido: $navori_allowed_list)"
  fi
  case "$navori_real" in
    "$navori_root"/*)
      navori_rel=${navori_real#"$navori_root"/}
      navori_ok=0
      while IFS= read -r navori_prefix; do
        [ -n "$navori_prefix" ] || continue
        navori_prefix=${navori_prefix%/}
        case "$navori_rel" in
          "$navori_prefix" | "$navori_prefix"/*)
            navori_ok=1
            break
            ;;
        esac
      done <<EOF
$navori_allowed
EOF
      if [ "$navori_ok" -ne 1 ]; then
        block "$navori_role no escribe '$navori_path' (permitido: $navori_allowed_list)"
      fi
      ;;
    "$navori_root")
      block "$navori_role no escribe '$navori_path' (permitido: $navori_allowed_list)"
      ;;
    *)
      if ! nv_in_temp "$navori_real"; then
        block "$navori_role no escribe '$navori_path' (fuera del repo; permitido: $navori_allowed_list)"
      fi
      ;;
  esac
done <<EOF
$(nv_edited_paths)
EOF

navori_audit_verdict="allow"
navori_audit_reason="rutas dentro del rol"
exit 0
