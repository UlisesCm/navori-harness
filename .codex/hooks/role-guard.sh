# Lexical normalization of an absolute path: drops `.` and empty segments and
# folds `..`. Written with parameter expansion only (no word splitting), so it
# behaves the same under bash and zsh.
nv_normalize() {
  local rest=${1#/} seg out=""
  while [ -n "$rest" ]; do
    case "$rest" in
      */*)
        seg=${rest%%/*}
        rest=${rest#*/}
        ;;
      *)
        seg=$rest
        rest=""
        ;;
    esac
    case "$seg" in
      "" | .) ;;
      ..) out=${out%/*} ;;
      *) out="$out/$seg" ;;
    esac
  done
  printf '%s' "${out:-/}"
}

# Physical form of an absolute normalized path: the nearest existing ancestor is
# resolved with `cd -P`, and the not-yet-existing tail is appended as written.
# Empty output means it could not be resolved.
nv_realdir() {
  local d=$1 suffix="" real parent
  while [ ! -e "$d" ] && [ ! -L "$d" ] && [ "$d" != "/" ]; do
    suffix="/${d##*/}$suffix"
    d=${d%/*}
    [ -n "$d" ] || d=/
  done
  if [ -d "$d" ]; then
    real=$(cd -P "$d" 2>/dev/null && pwd -P) || return 0
  else
    parent=${d%/*}
    [ -n "$parent" ] || parent=/
    real=$(cd -P "$parent" 2>/dev/null && pwd -P) || return 0
    real="${real%/}/${d##*/}"
  fi
  printf '%s' "${real%/}$suffix"
}

# Follow a leaf symlink chain (bounded) on top of `nv_realdir`.
nv_realpath() {
  local p=$1 n=0 target
  while :; do
    p=$(nv_realdir "$p")
    [ -n "$p" ] || return 0
    if [ -L "$p" ] && [ "$n" -lt 20 ]; then
      target=$(readlink "$p") || break
      case "$target" in
        /*) p=$(nv_normalize "$target") ;;
        *) p=$(nv_normalize "${p%/*}/$target") ;;
      esac
      n=$((n + 1))
    else
      break
    fi
  done
  printf '%s' "$p"
}

# 0 when the physical path sits under an OS temp root (resolved the same way, so
# `/tmp` -> `/private/tmp` and `$TMPDIR` -> `/private/var/folders/...` compare).
nv_in_temp() {
  local root real
  for root in /tmp /var/tmp "${TMPDIR:-}"; do
    [ -n "$root" ] || continue
    real=$(cd -P "$root" 2>/dev/null && pwd -P) || continue
    case "$1" in
      "${real%/}"/*) return 0 ;;
    esac
  done
  return 1
}

