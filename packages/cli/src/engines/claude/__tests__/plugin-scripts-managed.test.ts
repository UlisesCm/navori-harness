/**
 * #637 — a plugin script is no longer the one file navori cannot prove it wrote.
 *
 * Every other generated file — hooks, agents, skills — carries a
 * `navori:managed` marker with an id, a hash and a version. `scriptAssets` was
 * `{ src, dest, exec }`, so a script's only mark was a prose comment
 * (`# Generated by @navori/plugin-<id>`) that nothing enforces. The authorship
 * test could therefore only ever answer `foreign`, and navori never deletes
 * what it cannot prove it wrote — which is the correct rule, applied to a file
 * it had no way of claiming.
 *
 * Two consequences, and the first PREDATES any monorepo work: the engine prune
 * left a disabled plugin's scripts behind forever, and spec 0018's workspace
 * trim had to skip `scripts/` entirely.
 *
 * The id is DERIVED, never declared: every plugin already installed gains a
 * provable marker on the next render, with no manifest edit, and an id nobody
 * types is an id nobody can typo into a collision.
 */

let cwd: string;

function config(preset = "custom"): NavoriConfig {
  return NavoriConfigSchema.parse({
    name: "scripts-demo",
    engines: ["claude"],
    preset,
    branchBase: "main",
    qualityGate: { fast: "pnpm lint", full: "pnpm test" },
    plugins: { jscpd: { enabled: true } },
  });
}

beforeEach(() => {
  cwd = mkdtempSync(join(tmpdir(), "navori-plugin-scripts-"));
});

afterEach(() => {
  rmSync(cwd, { recursive: true, force: true });
});

const script = (): string => join(cwd, ".claude/scripts/check-jscpd.sh");

describe("scripts de plugin: marcador propio (#637)", () => {
  it("el script renderizado lleva marcador con el plugin como source", () => {
    renderClaudeEngine(cwd, config());
    expect(existsSync(script())).toBe(true);
    const body = readFileSync(script(), "utf-8");
    expect(body).toMatch(/^# navori:managed start id="jscpd-script-check-jscpd"/);
    expect(body).toContain('source="@navori/plugin-jscpd"');
    expect(body).toMatch(/hash="[0-9a-f]+"/);
  });

  it("navori PUEDE probar que lo escribió — el punto entero del issue", () => {
    renderClaudeEngine(cwd, config());
    expect(navoriAuthorship(script())).toBe("ours");
  });

  it("el shebang queda tras el marcador, como en los hooks", () => {
    // Seguro aquí por la misma razón que allá: las 28 referencias a estos
    // archivos en los assets los invocan como `bash <archivo>`, nunca directo.
    // Un renderer shebang-aware cambiaría los bytes de TODO archivo managed del
    // parque para arreglar nada.
    renderClaudeEngine(cwd, config());
    const [primera, segunda] = readFileSync(script(), "utf-8").split("\n");
    expect(primera).toContain("navori:managed start");
    expect(segunda).toBe("#!/usr/bin/env bash");
  });

  it("un script editado DENTRO del bloque no se sobrescribe: se salta y se reporta", () => {
    // Protección que los scripts no tenían: antes eran una copia cruda y el
    // render los pisaba en cada corrida, sin decir nada.
    renderClaudeEngine(cwd, config());
    const original = readFileSync(script(), "utf-8");
    writeFileSync(script(), original.replace("#!/usr/bin/env bash", "#!/usr/bin/env bash\n# mío"));

    const result = renderClaudeEngine(cwd, config());
    expect(readFileSync(script(), "utf-8")).toContain("# mío");
    expect(result.skipped.some((sk) => sk.path.endsWith("check-jscpd.sh"))).toBe(true);
  });

  it("MIGRA un script legacy sin marcador: lo reemplaza, no lo duplica", () => {
    // El bug que este caso fija, medido: `injectManagedSection` sobre un archivo
    // sin marca AÑADE el bloque al final, así que un script de 133 líneas quedó
    // en 269 — el original seguido de una copia marcada. Es correcto para un
    // CLAUDE.md que gana un bloque; es destructivo para un script que ES el
    // bloque.
    renderClaudeEngine(cwd, config());
    const marcado = readFileSync(script(), "utf-8");
    const lineasMarcado = marcado.split("\n").length;

    // Reconstruye el estado legacy: el mismo contenido, sin las 2 líneas de
    // marcador — que es exactamente lo que había en disco antes de #637.
    const legacy = marcado
      .split("\n")
      .filter((l) => !l.includes("navori:managed"))
      .join("\n");
    writeFileSync(script(), legacy);

    renderClaudeEngine(cwd, config());
    const despues = readFileSync(script(), "utf-8");
    expect(despues.split("\n").length).toBe(lineasMarcado);
    expect((despues.match(/navori:managed/g) ?? []).length).toBe(2);
    expect(despues).toMatch(/^# navori:managed start/);
  });

  it("un legacy que el usuario editó se salta, no se pisa", () => {
    // Sin marcador no hay hash que comparar, así que la única prueba honesta es
    // reproducir la salida vieja y comparar. Distinto ⇒ es del usuario.
    renderClaudeEngine(cwd, config());
    const legacy = readFileSync(script(), "utf-8")
      .split("\n")
      .filter((l) => !l.includes("navori:managed"))
      .join("\n");
    writeFileSync(script(), legacy + "\n# lo edité yo\n");

    const result = renderClaudeEngine(cwd, config());
    expect(readFileSync(script(), "utf-8")).toContain("# lo edité yo");
    expect(result.skipped.some((sk) => sk.path.endsWith("check-jscpd.sh"))).toBe(true);
  });

  it("sync-file-resolve: the skip of an in-block edit carries the forced render (marker kept, exec preserved)", () => {
    renderClaudeEngine(cwd, config());
    const original = readFileSync(script(), "utf-8");
    const edited = original.replace("#!/usr/bin/env bash", "#!/usr/bin/env bash\n# mío");
    writeFileSync(script(), edited);

    const sk = renderClaudeEngine(cwd, config()).skipped.find((s) =>
      s.path.endsWith("check-jscpd.sh"),
    );
    expect(sk?.resolution?.basis).toBe(edited);
    expect(sk?.resolution?.content).toBe(original);
    expect(sk?.resolution?.chmodExec).toBe(true);
  });

  it("sync-file-resolve: a markerless user-edited legacy script is skipped with NO resolution", () => {
    renderClaudeEngine(cwd, config());
    const legacy = readFileSync(script(), "utf-8")
      .split("\n")
      .filter((l) => !l.includes("navori:managed"))
      .join("\n");
    writeFileSync(script(), `${legacy}\n# user line\n`);
    const sk = renderClaudeEngine(cwd, config()).skipped.find((s) =>
      s.path.endsWith("check-jscpd.sh"),
    );
    expect(sk?.status).toBe("user-modified-skipped");
    expect(sk?.resolution).toBeUndefined();
  });

  it("I1: an in-block edit on a script from a NEWER navori is downgrade-skipped, no resolution", () => {
    renderClaudeEngine(cwd, config());
    const body = readFileSync(script(), "utf-8");
    const newer = body
      .replace(/version="[^"]*"/, 'version="999.0.0"')
      .replace("#!/usr/bin/env bash", "#!/usr/bin/env bash\n# futuro");
    writeFileSync(script(), newer);

    const sk = renderClaudeEngine(cwd, config()).skipped.find((s) =>
      s.path.endsWith("check-jscpd.sh"),
    );
    expect(sk?.status).toBe("downgrade-skipped");
    expect(sk?.resolution).toBeUndefined();
    expect(readFileSync(script(), "utf-8")).toBe(newer);
  });

  it("the skip reason points at sync when resolvable and keeps the manual exit otherwise", () => {
    renderClaudeEngine(cwd, config());
    const original = readFileSync(script(), "utf-8");
    writeFileSync(script(), original.replace("#!/usr/bin/env bash", "#!/usr/bin/env bash\n# mío"));
    const resolvable = renderClaudeEngine(cwd, config()).skipped.find((s) =>
      s.path.endsWith("check-jscpd.sh"),
    );
    expect(resolvable?.reason).toBe(tc("es").engine.managedFileEditedResolvable);

    const legacy = original
      .split("\n")
      .filter((l) => !l.includes("navori:managed"))
      .join("\n");
    writeFileSync(script(), `${legacy}\n# user line\n`);
    const manual = renderClaudeEngine(cwd, config()).skipped.find((s) =>
      s.path.endsWith("check-jscpd.sh"),
    );
    expect(manual?.reason).toBe(tc("es").engine.managedBlockEditedByHand);
  });

  it("es idempotente: un segundo render no reescribe el script", () => {
    renderClaudeEngine(cwd, config());
    const second = renderClaudeEngine(cwd, config());
    expect(second.written.some((w) => w.path.endsWith("check-jscpd.sh"))).toBe(false);
  });

  // Covers: R20
  it("preserves an edited plugin script on disable across repeated renders", () => {
    renderClaudeEngine(cwd, config());
    const edited = readFileSync(script(), "utf-8").replace(
      "#!/usr/bin/env bash",
      "#!/usr/bin/env bash\n# user-owned edit",
    );
    writeFileSync(script(), edited);
    const disabled = NavoriConfigSchema.parse({
      ...config(),
      plugins: { jscpd: { enabled: false } },
    });

    const first = renderClaudeEngine(cwd, disabled);
    expect(readFileSync(script(), "utf-8")).toBe(edited);
    expect(first.written.some((entry) => entry.path.endsWith("check-jscpd.sh"))).toBe(false);
    const second = renderClaudeEngine(cwd, disabled);
    expect(readFileSync(script(), "utf-8")).toBe(edited);
    expect(second.written.some((entry) => entry.path.endsWith("check-jscpd.sh"))).toBe(false);
  });

  // Covers: R20
  it("does not retire a script carrying a newer managed version", () => {
    renderClaudeEngine(cwd, config());
    const newer = readFileSync(script(), "utf-8").replace(/version="[^"]+"/, 'version="999.0.0"');
    writeFileSync(script(), newer);
    const disabled = NavoriConfigSchema.parse({
      ...config(),
      plugins: { jscpd: { enabled: false } },
    });
    renderClaudeEngine(cwd, disabled);
    expect(readFileSync(script(), "utf-8")).toBe(newer);
  });

  // Covers: R20
  it("warns when a preserved script may remain active in settings that could not be updated", () => {
    renderClaudeEngine(cwd, config());
    const edited = readFileSync(script(), "utf-8").replace(
      "#!/usr/bin/env bash",
      "#!/usr/bin/env bash\n# user-owned edit",
    );
    writeFileSync(script(), edited);
    const settingsPath = join(cwd, ".claude/settings.json");
    const settings = readFileSync(settingsPath, "utf-8");
    writeFileSync(settingsPath, settings.slice(0, -2));
    const disabled = NavoriConfigSchema.parse({
      ...config(),
      plugins: { jscpd: { enabled: false } },
    });

    const result = renderClaudeEngine(cwd, disabled);
    expect(readFileSync(script(), "utf-8")).toBe(edited);
    expect(result.warnings).toContainEqual(
      expect.stringContaining("ALERTA: .claude/scripts/check-jscpd.sh"),
    );
  });
});

