import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, realpathSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { RETIRED_PLUGINS, RETIRED_PLUGIN_SUB_BLOCKS } from "../../../lib/config/plugins.ts";
import { readCliVersion } from "../../../lib/render/bundled-assets.ts";
import { injectManagedSection } from "../../../lib/render/marker.ts";

/**
 * Fixtures for the retired-plugin tests. They use SYNTHETIC retired entries so the
 * policy is exercised without depending on which real plugins are retired today
 * (`cognitive` stays the only real one, and it carries `deleteForeign`).
 */

/** Strict (no `deleteForeign`) synthetic retired plugin. */
export const SYN_ID = "zzdemo";
export const SYN_SCRIPT = "check-zzdemo.sh";
export const SYN_BLOCK = "zzdemo-protocol";
export const SYN_SUB_BLOCK = "zzdemo-review-extension";
/** A sub-block hosted by a skill that Codex also renders, so its target is not an orphan skill. */
export const SYN_CODEX_SUB_BLOCK = "zzdemo-codex-extension";
/** Target of the synthetic sub-block: a skill both engines can host. */
export const SYN_SKILL_ID = "zz-skill";

/** Registers the synthetic retired plugin; returns the function that removes it. */
export function registerSyntheticRetired(): () => void {
  RETIRED_PLUGINS[SYN_ID] = {
    removedIn: "#999",
    blockIds: [SYN_BLOCK],
    assets: [`.claude/scripts/${SYN_SCRIPT}`],
  };
  RETIRED_PLUGIN_SUB_BLOCKS[SYN_ID] = {
    retiredIn: "#999",
    entries: [
      { id: SYN_SUB_BLOCK, targetPath: `.claude/skills/${SYN_SKILL_ID}/SKILL.md` },
      { id: SYN_CODEX_SUB_BLOCK, targetPath: ".claude/skills/review-diff/SKILL.md" },
      { id: "zzdemo-agent-extension", targetPath: ".claude/agents/zz-agent.md" },
    ],
  };
  return () => {
    delete RETIRED_PLUGINS[SYN_ID];
    delete RETIRED_PLUGIN_SUB_BLOCKS[SYN_ID];
  };
}

/** A temp git repo (realpath'd, as git reports it). */
export function makeRepo(): string {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), "navori-retired-")));
  execFileSync("git", ["init", "-q"], { cwd: dir });
  return dir;
}

/** What navori renders for a retired plugin's script: one shell managed block, nothing else. */
export function markedScript(extraBody = ""): string {
  return injectManagedSection(
    "",
    "zzdemo-script-check-zzdemo",
    `#!/usr/bin/env bash\n# Generated by @navori/plugin-zzdemo.\n# ${SYN_SCRIPT}\necho zzdemo ${extraBody}\n`,
    { source: "@navori/plugin-zzdemo", version: readCliVersion() },
    "shell",
  ).output;
}

/** Writes `content` at `rel` under `cwd` (creating parents) and returns the absolute path. */
export function put(cwd: string, rel: string, content: string): string {
  const abs = join(cwd, rel);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, content);
  return abs;
}
