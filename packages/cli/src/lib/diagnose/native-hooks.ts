import { execFileSync } from "node:child_process";
import {
  closeSync,
  existsSync,
  openSync,
  readSync,
  readdirSync,
  readFileSync,
  statSync,
} from "node:fs";
import { basename, dirname, join, relative, resolve, sep } from "node:path";

/**
 * Detection of native git hooks (spec 0045 D3, R5/R6). Read-only: it inspects
 * files and asks git where the hooks live, and never executes a hook.
 */

/** The git events whose native hook can stand in for navori's commit gate. */
export const NATIVE_HOOK_EVENTS = ["pre-commit", "pre-push"] as const;
export type NativeHookEvent = (typeof NATIVE_HOOK_EVENTS)[number];

export type NativeHookManager = "husky" | "lefthook" | "pre-commit" | "plain";

/**
 * Why a hook counts as absent (R6). `unknown-git` covers both "git failed" and
 * "git older than 2.9" (no `core.hooksPath`): an ambiguous detection is absent.
 */
export type NativeHookAbsence =
  | "unknown-git"
  | "missing"
  | "not-executable"
  | "empty"
  | "husky-stub"
  | "no-lefthook-config"
  | "no-pre-commit-config"
  | "pre-commit-stage-missing"
  | "no-user-content";

export interface NativeHookState {
  event: NativeHookEvent;
  active: boolean;
  /** Manager that generated the hook, when the file exists and was recognised. */
  manager: NativeHookManager | null;
  /** Absolute path of the hook file as git resolves it; null when git is unknown. */
  path: string | null;
  /** Set exactly when `active` is false. */
  absence: NativeHookAbsence | null;
}

export interface NativeHooksDetection {
  /** `git rev-parse --show-toplevel` of `cwd`; null outside a work tree. */
  top: string | null;
  hooksDir: string | null;
  /** Output of `git --version`, for the "unknown" message (M6). */
  gitVersion: string | null;
  hooks: Record<NativeHookEvent, NativeHookState>;
}

function git(cwd: string, args: string[]): string | null {
  try {
    return execFileSync("git", ["-C", cwd, ...args], {
      encoding: "utf-8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
}

/** `core.hooksPath` exists since git 2.9. */
function supportsHooksPath(version: string | null): boolean {
  const m = version?.match(/(\d+)\.(\d+)/);
  if (!m) return false;
  const major = Number(m[1]);
  return major > 2 || (major === 2 && Number(m[2]) >= 9);
}

const absent = (
  event: NativeHookEvent,
  path: string | null,
  absence: NativeHookAbsence,
  manager: NativeHookManager | null = null,
): NativeHookState => ({ event, active: false, manager, path, absence });

/** A non-shebang, non-comment, non-blank line: something the user wrote. */
function hasUserContent(text: string): boolean {
  return text.split("\n").some((raw) => {
    const line = raw.trim();
    return line !== "" && !line.startsWith("#");
  });
}

function isNonEmptyRegular(path: string): boolean {
  try {
    const st = statSync(path);
    return st.isFile() && st.size > 0;
  } catch {
    return false;
  }
}

function readSafe(path: string): string {
  try {
    return readFileSync(path, "utf-8");
  } catch {
    return "";
  }
}

const HUSKY_STUB = /^\s*\.\s+"\$\(dirname "\$0"\)\/h"\s*$/m;
const PRE_COMMIT_HEADER = /File generated by pre-commit/;
const LEFTHOOK_CONFIG = /^\.?lefthook(-local)?\.(ya?ml|json|toml)$/;

/** Per-event lefthook declaration patterns (json key, toml table, yaml key), static so no regex is built from input. */
const LEFTHOOK_EVENT: Record<NativeHookEvent, { json: RegExp; toml: RegExp; yaml: RegExp }> = {
  "pre-commit": { json: /"pre-commit"\s*:/, toml: /^\[pre-commit[\].]/m, yaml: /^pre-commit\s*:/m },
  "pre-push": { json: /"pre-push"\s*:/, toml: /^\[pre-push[\].]/m, yaml: /^pre-push\s*:/m },
};

function lefthookDeclares(top: string, event: NativeHookEvent): boolean {
  let names: string[];
  try {
    names = readdirSync(top).filter((n) => LEFTHOOK_CONFIG.test(n));
  } catch {
    return false;
  }
  return names.some((name) => {
    const text = readSafe(join(top, name));
    const re = LEFTHOOK_EVENT[event];
    if (name.endsWith(".json")) return re.json.test(text);
    if (name.endsWith(".toml")) return re.toml.test(text);
    return re.yaml.test(text);
  });
}

function classify(
  event: NativeHookEvent,
  top: string,
  hooksDir: string,
  file: string,
): NativeHookState {
  if (!existsSync(file)) return absent(event, file, "missing");
  let executable = false;
  try {
    const st = statSync(file);
    if (!st.isFile()) return absent(event, file, "missing");
    if (st.size === 0) return absent(event, file, "empty");
    executable = (st.mode & 0o111) !== 0;
  } catch {
    return absent(event, file, "missing");
  }
  if (!executable) return absent(event, file, "not-executable");

  const text = readSafe(file);
  const active = (manager: NativeHookManager): NativeHookState => ({
    event,
    active: true,
    manager,
    path: file,
    absence: null,
  });

  // husky v9: the file git runs is a stub; the user's script lives one level up.
  const huskyDir = basename(hooksDir) === "_" && existsSync(join(hooksDir, "h"));
  if (huskyDir || HUSKY_STUB.test(text)) {
    return isNonEmptyRegular(join(dirname(hooksDir), event))
      ? active("husky")
      : absent(event, file, "husky-stub", "husky");
  }
  if (/lefthook/.test(text)) {
    return lefthookDeclares(top, event)
      ? active("lefthook")
      : absent(event, file, "no-lefthook-config", "lefthook");
  }
  if (PRE_COMMIT_HEADER.test(text)) {
    const config = join(top, ".pre-commit-config.yaml");
    if (!existsSync(config)) return absent(event, file, "no-pre-commit-config", "pre-commit");
    if (event === "pre-push" && !/pre-push/.test(readSafe(config)))
      return absent(event, file, "pre-commit-stage-missing", "pre-commit");
    return active("pre-commit");
  }
  return hasUserContent(text) ? active("plain") : absent(event, file, "no-user-content", "plain");
}

/**
 * Evaluates `pre-commit` and `pre-push` in the clone or worktree holding `cwd`.
 * The hooks directory comes from `git rev-parse --git-path hooks` run in the
 * toplevel, so a relative `core.hooksPath` resolves per worktree.
 */
export function detectNativeHooks(cwd: string): NativeHooksDetection {
  const gitVersion = git(cwd, ["--version"]);
  const top = git(cwd, ["rev-parse", "--show-toplevel"]);
  const rel = top === null ? null : git(top, ["rev-parse", "--git-path", "hooks"]);
  if (top === null || rel === null || rel === "" || !supportsHooksPath(gitVersion)) {
    const unknown = (event: NativeHookEvent): NativeHookState => absent(event, null, "unknown-git");
    return {
      top,
      hooksDir: null,
      gitVersion,
      hooks: { "pre-commit": unknown("pre-commit"), "pre-push": unknown("pre-push") },
    };
  }
  const hooksDir = resolve(top, rel);
  return {
    top,
    hooksDir,
    gitVersion,
    hooks: {
      "pre-commit": classify("pre-commit", top, hooksDir, join(hooksDir, "pre-commit")),
      "pre-push": classify("pre-push", top, hooksDir, join(hooksDir, "pre-push")),
    },
  };
}

/** Paths from `git worktree list --porcelain`; empty outside git. */
export function listWorktreePaths(cwd: string): string[] {
  const out = git(cwd, ["worktree", "list", "--porcelain"]);
  if (out === null) return [];
  return out
    .split("\n")
    .filter((l) => l.startsWith("worktree "))
    .map((l) => l.slice("worktree ".length));
}

/** One file that can run a command when a commit, a push or CI fires. */
export interface HookSource {
  /** Absolute path of the file. */
  path: string;
  text: string;
}

/** Each hook source is read up to this many bytes: a script that names a path does so early. */
const HOOK_SOURCE_MAX_BYTES = 256 * 1024;
/** Bound on `.husky/**` and `.lefthook/**` walks, so a pathological tree cannot stall a render. */
const HOOK_SOURCE_MAX_FILES = 200;
const HOOK_SOURCE_MAX_DEPTH = 4;

/** First `HOOK_SOURCE_MAX_BYTES` of a regular file; null for anything else or on error. */
function readCapped(path: string): string | null {
  try {
    if (!statSync(path).isFile()) return null;
    const fd = openSync(path, "r");
    try {
      const buf = Buffer.alloc(HOOK_SOURCE_MAX_BYTES);
      const n = readSync(fd, buf, 0, HOOK_SOURCE_MAX_BYTES, 0);
      return buf.subarray(0, n).toString("utf-8");
    } finally {
      closeSync(fd);
    }
  } catch {
    return null;
  }
}

/** Regular files under `dir`, depth- and count-capped. Symlinked directories are not followed. */
function filesUnder(dir: string, depth = 0, budget = { left: HOOK_SOURCE_MAX_FILES }): string[] {
  if (depth > HOOK_SOURCE_MAX_DEPTH) return [];
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const out: string[] = [];
  for (const entry of entries) {
    if (budget.left <= 0) break;
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...filesUnder(abs, depth + 1, budget));
    else if (entry.isFile()) {
      budget.left -= 1;
      out.push(abs);
    }
  }
  return out;
}

/** Repo-relative path tokens (`scripts/x.sh`, `./a/b`) a hook text names, for one hop of delegation. */
const DELEGATED_PATH = /(?:^|[\s"'=(])((?:\.{1,2}\/)?[\w.@+-]+(?:\/[\w.@+-]+)+)/g;

/**
 * Every file that may invoke a script by name: the git hooks directory git
 * resolves (`core.hooksPath` honoured, all events), the husky / lefthook /
 * pre-commit / overcommit configs, `package.json`, `Makefile` and the GitHub
 * workflows. Read-only and bounded; shared by `render` (to keep a retired script
 * something still calls) and `doctor` (to warn about a reference to a missing one).
 *
 * One hop of delegation is followed: a repo-relative path named by a hook-entry
 * file (the hooks directory, `.husky/**`) is read too when it lives inside the
 * repo. NOT detected, and documented as such: two or more hops, paths built at
 * runtime, callers outside the repo (IDE tasks, other CI systems) and lefthook
 * `extends`/`remotes`.
 *
 * Spawns `git` (two processes), so callers invoke it lazily, once per render.
 */
export function readHookSources(cwd: string): HookSource[] {
  const top = git(cwd, ["rev-parse", "--show-toplevel"]);
  const roots = [...new Set([resolve(cwd), ...(top ? [resolve(top)] : [])])];
  const seen = new Map<string, HookSource>();
  const add = (path: string): string | null => {
    const abs = resolve(path);
    const known = seen.get(abs);
    if (known) return known.text;
    const text = readCapped(abs);
    if (text !== null) seen.set(abs, { path: abs, text });
    return text;
  };

  // Hook entry points: the files git (or husky) runs directly. One hop is followed from these.
  const entries: string[] = [];
  const hooksRel = top ? git(top, ["rev-parse", "--git-path", "hooks"]) : null;
  if (top && hooksRel) {
    const hooksDir = resolve(top, hooksRel);
    try {
      for (const name of readdirSync(hooksDir)) {
        if (!name.endsWith(".sample")) entries.push(join(hooksDir, name));
      }
    } catch {
      // No hooks directory: nothing to read there.
    }
  }
  for (const root of roots) entries.push(...filesUnder(join(root, ".husky")));

  for (const entry of entries) {
    const text = add(entry);
    if (text === null) continue;
    for (const m of text.matchAll(DELEGATED_PATH)) {
      const candidate = m[1];
      if (candidate === undefined) continue;
      for (const root of roots) {
        const abs = resolve(root, candidate);
        const rel = relative(root, abs);
        if (rel === "" || rel.startsWith("..") || rel.startsWith(sep)) continue;
        add(abs);
      }
    }
  }

  for (const root of roots) {
    for (const dir of [root, join(root, ".config")]) {
      let names: string[] = [];
      try {
        names = readdirSync(dir);
      } catch {
        // Missing directory.
      }
      for (const name of names) {
        if (/^\.?lefthook/.test(name)) add(join(dir, name));
      }
    }
    for (const file of filesUnder(join(root, ".lefthook"))) add(file);
    for (const name of [".pre-commit-config.yaml", ".overcommit.yml", "package.json", "Makefile"]) {
      add(join(root, name));
    }
    try {
      for (const name of readdirSync(join(root, ".github/workflows"))) {
        if (/\.ya?ml$/.test(name)) add(join(root, ".github/workflows", name));
      }
    } catch {
      // No workflows.
    }
  }
  return [...seen.values()];
}
