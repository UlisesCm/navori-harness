/** How the prune reads the outside of one file kind. */
export interface ScaffoldKind {
  /**
   * Marker syntax the writer of this kind uses, decided by the file's extension
   * (never sniffed from its bytes). `null` for an extension no engine writes
   * markers into: the file is kept whole, which is the safe direction.
   */
  style: CommentStyle | null;
  /** Trimmed non-blank lines navori seeds outside the blocks of this kind. */
  lines: ReadonlySet<string>;
  /** Navori seeds frontmatter before the blocks (skill/agent/context `.md`, the Cursor rule). */
  frontmatter: boolean;
  /** The kind may open with a shebang on its first line (hook/script `.sh`). */
  shebang: boolean;
  /**
   * The kind ends with the extension zone the bundled assets seed (`isSeededZone`):
   * what is left outside the blocks must equal one of them EXACTLY.
   */
  seededZone: ZonePool | null;
}

/** Marker syntax per extension, as the engines write it: `.sh`, `.toml`, `.yaml`/`.yml`
 *  (Codex `agents/openai.yaml`) and `.rules` take shell comments; `.md`/`.mdc` take html. */
const STYLE_BY_EXTENSION: Readonly<Record<string, CommentStyle>> = {
  ".sh": "shell",
  ".toml": "shell",
  ".yaml": "shell",
  ".yml": "shell",
  ".rules": "shell",
  ".md": "html",
  ".mdc": "html",
};

/** Directories whose `.md` files navori writes with frontmatter before the blocks. */
const FRONTMATTER_DIRS: readonly string[] = [
  ".claude/skills/",
  ".claude/agents/",
  ".claude/context/",
  ".agents/skills/",
];

/** Text with CRLF folded, trailing spaces dropped and blank runs capped at ONE blank line. */
export function normalizeZone(text: string): string {
  return text
    .replace(/\r\n/g, "\n")
    .split("\n")
    .map((line) => line.trimEnd())
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/** Which pool of bundled extension zones a file kind compares against. */
export type ZonePool = "script" | "markdown";

interface RawZones {
  script: string[];
  markdown: string[];
}

let rawZones: RawZones | null = null;

/**
 * The extension zones the bundled assets seed, UNRENDERED: the template each
 * engine writes after the managed block, taken through `parseAsset` so this
 * module and the renderer agree on what a `navori:user-section` line is. Hook
 * zones (shell scripts) and agent/skill zones (Markdown) are separate pools: a
 * hook zone is never scaffold in a Markdown file. One walk per process.
 */
function bundledZones(): RawZones {
  if (rawZones) return rawZones;
  const found: RawZones = { script: [], markdown: [] };
  const walk = (dir: string, depth: number): void => {
    if (depth > 6) return;
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full, depth + 1);
      else if (entry.isFile() && (entry.name.endsWith(".sh") || entry.name.endsWith(".md"))) {
        const script = entry.name.endsWith(".sh");
        const asset = parseAsset(readFileSync(full, "utf-8"), script ? "shell" : "html");
        if (asset.userTemplate) (script ? found.script : found.markdown).push(asset.userTemplate);
      }
    }
  };
  walk(join(getCoreRoot(), "core-assets"), 0);
  rawZones = found;
  return found;
}

/** The rendered zones of one config, per pool. */
const renderedZones = new WeakMap<NavoriConfig, Record<ZonePool, ReadonlySet<string>>>();

/**
 * Every zone text a render could have left in a file written with `config`: the
 * bundled templates interpolated exactly as the engines do, in TWO renders. The
 * current one, and the one `init` produced, when `project.criticalAreas` and
 * `project.legacyPaths` had not been declared yet. A seeded zone is written once
 * and stays the user's afterwards, so a repo that later filled those in still
 * holds the init-time text. Both are compared by exact string equality.
 */
function zonesFor(config: NavoriConfig): Record<ZonePool, ReadonlySet<string>> {
  const cached = renderedZones.get(config);
  if (cached) return cached;
  // An empty list renders as unset (the interpolator's default text), the shape `init` wrote.
  // Without a `project` section the current render already is the init-time one.
  const atInit: NavoriConfig = config.project
    ? { ...config, project: { ...config.project, criticalAreas: [], legacyPaths: [] } }
    : config;
  const render = (templates: readonly string[]): Set<string> =>
    new Set(
      templates.flatMap((template) =>
        [config, atInit].map((cfg) => normalizeZone(interpolate(template, cfg))),
      ),
    );
  const raw = bundledZones();
  const zones = { script: render(raw.script), markdown: render(raw.markdown) };
  renderedZones.set(config, zones);
  return zones;
}

/**
 * True when `text` (normalized) is EXACTLY a zone the bundled assets of this pool
 * seed, rendered with `config`. No pattern matching: text the user appended to a
 * seeded line, or an edit inside the seeded comment, makes it differ and keeps the file.
 */
export function isSeededZone(pool: ZonePool, text: string, config: NavoriConfig): boolean {
  return zonesFor(config)[pool].has(text);
}

const NO_LINES: ReadonlySet<string> = new Set();

/**
 * The scaffold of the file at `rel` (repo-relative, `/`-separated), by path and
 * extension — the same split `ENGINE_OUTPUTS` declares (`style` per entry).
 * Anything unrecognised gets NO scaffold: every non-blank line outside its blocks
 * counts as the user's.
 *
 * Frontmatter is exempt wholesale only for skill/agent/context files: navori writes
 * it from the asset, and comparing it field by field needs a fresh render of that
 * asset. The cost is a user's edit to that frontmatter not keeping the file alive;
 * the file is backed up before it is deleted. The Cursor rule's frontmatter is
 * compared exactly, as part of `CURSOR_HEADER`.
 */
export function scaffoldKindOf(rel: string): ScaffoldKind {
  const base = rel.slice(rel.lastIndexOf("/") + 1);
  const dot = base.lastIndexOf(".");
  const ext = dot > 0 ? base.slice(dot) : "";
  const style = base === ".gitignore" ? "shell" : (STYLE_BY_EXTENSION[ext] ?? null);
  const kind: ScaffoldKind = {
    style,
    frontmatter: false,
    shebang: false,
    seededZone: null,
    lines: NO_LINES,
  };
  if (base === "CLAUDE.md") {
    return {
      ...kind,
      lines: linesOf(
        USER_SECTION_START,
        USER_SECTION_END,
        ...SUPPORTED_LANGS.map((lang) => tc(lang).common.userSectionPlaceholder),
      ),
    };
  }
  if (rel === "AGENTS.md") {
    return {
      ...kind,
      lines: linesOf(
        AGENTS_MD_HEADER,
        AGENTS_MD_USER_SECTION,
        CODEX_AGENTS_HEADER,
        CODEX_AGENTS_TRAILER,
      ),
    };
  }
  if (rel === ".github/copilot-instructions.md") {
    return { ...kind, lines: linesOf(COPILOT_HEADER, COPILOT_USER_SECTION) };
  }
  if (rel === ".cursor/rules/navori.mdc") {
    // Its frontmatter is part of CURSOR_HEADER and compared line by line like the rest.
    return { ...kind, lines: linesOf(CURSOR_HEADER, CURSOR_USER_SECTION) };
  }
  if (rel === ".codex/config.toml") return { ...kind, lines: linesOf(CODEX_CONFIG_HEADER) };
  if (rel === ".codex/rules/navori.rules") return { ...kind, lines: linesOf(CODEX_RULES_HEADER) };
  if (base === ".gitignore") {
    return {
      ...kind,
      lines: linesOf(...SUPPORTED_LANGS.map((lang) => tc(lang).render.gitignoreHeader)),
    };
  }
  if (ext === ".sh") return { ...kind, shebang: true, seededZone: "script" };
  if (ext === ".md" && FRONTMATTER_DIRS.some((dir) => rel.startsWith(dir))) {
    return { ...kind, frontmatter: true, seededZone: "markdown" };
  }
  return kind;
}

/** Trimmed non-blank lines of the seeds; the scaffold of the prose files is matched line by line. */
function linesOf(...seeds: readonly string[]): Set<string> {
  const out = new Set<string>();
  for (const seed of seeds) {
    for (const line of seed.split("\n")) {
      const t = line.trim();
      if (t !== "") out.add(t);
    }
  }
  return out;
}
