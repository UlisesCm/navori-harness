import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { scanForeignSkillIndexes } from "../foreign-skill-index.ts";

/**
 * #625 — a skill index written by ANOTHER harness that went stale.
 *
 * Field measurement across four repos of the workspace, all carrying a
 * checked-in `.atl/skill-registry.md` from gentle-ai: 22, 27, 21 and 48 indexed
 * skills, and ZERO of those paths resolving here — they are absolute paths of
 * the machine that generated them, frozen between 2026-06 and 2026-07.
 *
 * The check's whole value rests on one property, so most of this file is about
 * it: NO false positives. A live second harness must stay silent, or the
 * warning becomes noise people learn to skip — which is worse than not warning.
 */

let cwd: string;

beforeEach(() => {
  cwd = mkdtempSync(join(tmpdir(), "navori-foreign-"));
});

afterEach(() => {
  rmSync(cwd, { recursive: true, force: true });
});

/** Write `.atl/skill-registry.md` with one table row per given path. */
function writeRegistry(paths: string[], opts: { updated?: string } = {}): void {
  mkdirSync(join(cwd, ".atl"), { recursive: true });
  const header = [
    "# Skill Registry — demo",
    "",
    "<!-- Auto-generated by gentle-ai skill-registry refresh. -->",
    "",
    opts.updated === undefined ? "" : `Last updated: ${opts.updated}`,
    "",
    "| Skill | Description | Scope | Path |",
    "|---|---|---|---|",
  ];
  const rows = paths.map((p, i) => `| \`skill-${i}\` | does a thing | project | \`${p}\` |`);
  writeFileSync(join(cwd, ".atl", "skill-registry.md"), [...header, ...rows].join("\n"));
}

describe("scanForeignSkillIndexes — un índice ajeno con todas sus rutas muertas (#625)", () => {
  it("no reporta nada cuando el repo no tiene un segundo harness", () => {
    expect(scanForeignSkillIndexes(cwd)).toEqual([]);
  });

  it("reporta el índice cuando ninguna de sus rutas existe", () => {
    writeRegistry(
      [
        "/Users/ricardomarin/.claude/skills/chained-pr/SKILL.md",
        "/Users/ricardomarin/Documents/projects/bonum/bonum-nexus/.claude/skills/sdk/SKILL.md",
      ],
      { updated: "2026-06-04" },
    );
    const found = scanForeignSkillIndexes(cwd);
    expect(found).toHaveLength(1);
    expect(found[0]).toMatchObject({
      path: ".atl/skill-registry.md",
      indexed: 2,
      frozenAt: "2026-06-04",
    });
    expect(found[0]?.producer).toMatch(/gentle-ai/);
  });

  it("CALLA cuando alguna ruta sí resuelve — el harness ajeno está vivo", () => {
    // La propiedad que hace usable al check. Una sola ruta viva significa que
    // alguien está usando esa herramienta en esta máquina, y navori no tiene
    // nada que opinar sobre un índice que funciona.
    const live = join(cwd, "real-skill", "SKILL.md");
    mkdirSync(join(cwd, "real-skill"), { recursive: true });
    writeFileSync(live, "# vive");
    writeRegistry(["/Users/otro/.claude/skills/muerta/SKILL.md", live]);
    expect(scanForeignSkillIndexes(cwd)).toEqual([]);
  });

  it("calla ante un índice sin entradas: vacío no prueba obsolescencia", () => {
    writeRegistry([]);
    expect(scanForeignSkillIndexes(cwd)).toEqual([]);
  });

  it("reporta sin fecha cuando el archivo no declara una", () => {
    writeRegistry(["/Users/otro/.claude/skills/x/SKILL.md"]);
    expect(scanForeignSkillIndexes(cwd)[0]?.frozenAt).toBeNull();
  });

  it("extrae la ruta de la celda, no la celda entera (anti-falso-conteo)", () => {
    // Sin los backticks el patrón se traga el texto de la fila y ninguna ruta
    // resolvería jamás — el check "pasaría" siempre, por la razón equivocada.
    writeRegistry(["/Users/otro/.claude/skills/x/SKILL.md"]);
    const found = scanForeignSkillIndexes(cwd);
    expect(found[0]?.indexed).toBe(1);
  });

  it("no rompe con un archivo ilegible o basura", () => {
    mkdirSync(join(cwd, ".atl"), { recursive: true });
    writeFileSync(
      join(cwd, ".atl", "skill-registry.md"),
      "\u0000\u0001 contenido binario, no markdown",
    );
    expect(() => scanForeignSkillIndexes(cwd)).not.toThrow();
    expect(scanForeignSkillIndexes(cwd)).toEqual([]);
  });
});
