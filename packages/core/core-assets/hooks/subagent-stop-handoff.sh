#!/usr/bin/env bash
#
# SubagentStop lifecycle hook — handoff validator.
# Fires when a subagent finishes. The harness contract is that an implementer
# closes with `impl_<feature>.md` and a reviewer with `review_<feature>.md`
# under the engine's progress dir — those files ARE the handoff the leader (and the
# commit-pr-pilot) read. A subagent that returns having left an empty or
# structurally-broken handoff silently corrupts that chain. This hook catches
# the obvious failure modes deterministically.
#
# DESIGN — advisory, never blocking. Emits a user-facing `systemMessage` only;
# it NEVER returns `decision: block`. It has no way to know WHICH subagent just
# stopped (agent identity isn't reliably in scope for a shell hook), so it can't
# demand a specific file — it only flags handoff files that already exist but
# look broken:
#   - empty / whitespace-only, OR
#   - `impl_*.md` missing its terminal `Status:` marker, OR
#   - `review_*.md` missing a verdict (APPROVED / CHANGES_REQUESTED).
# It never invents an expectation, so a legitimate report never trips it, and a
# missing file is not flagged (a subagent may not produce a handoff at all).
# Accepted limitation: during parallel work a still-in-flight report from
# ANOTHER running subagent could momentarily look incomplete — advisory-only, so
# a false positive is a harmless note, never a block.
#
# The managed block is regenerated by `navori render`; do NOT edit by hand.
set -euo pipefail

# The payload was drained and discarded here; it is kept now because the audit
# recorder reads `session_id`/`cwd` out of it. Draining is still the point: an
# undrained stdin can leave the host writing into a closed pipe.
payload=$(cat 2>/dev/null) || payload=""

navori_audit_name="subagent-stop-handoff"
navori_audit_phase="SubagentStop"

# Where the problem set last REPORTED in this session is remembered (#560).
#
# The host fires this phase far more often than subagents finish: 117 executions
# for 19 subagents in the measured session, every one of them reporting the same
# broken handoff — the identical `systemMessage` injected 117 times. Running the
# check again is cheap; re-telling the reader something already told is not, and
# a note repeated on every firing is a note nobody reads by the third one.
#
# Parsed with parameter expansion, never jq: this must work whether or not
# audit-mode is on, and jq may not exist. Keyed by session AND repo so two
# sessions never silence each other. In the OS temp dir, so nothing lands in the
# user's tree and a reboot is a clean slate.
navori_handoff_key="anon"
case "$payload" in
  *'"session_id"'*)
    navori_handoff_key=${payload#*\"session_id\":}
    navori_handoff_key=${navori_handoff_key# }
    navori_handoff_key=${navori_handoff_key#\"}
    navori_handoff_key=${navori_handoff_key%%\"*}
    ;;
esac
case "$navori_handoff_key" in
  "" | *[!A-Za-z0-9_-]*) navori_handoff_key="anon" ;;
esac
navori_handoff_repo=${PWD##*/}
case "$navori_handoff_repo" in
  "" | *[!A-Za-z0-9_.-]*) navori_handoff_repo="repo" ;;
esac
navori_handoff_stamp="${TMPDIR:-/tmp}/navori-handoff-$navori_handoff_repo-$navori_handoff_key"

# Fallback no-ops, overwritten by the real definitions the include brings in.
# They exist because this hook is FAIL-OPEN: if the file ever runs WITHOUT its
# includes expanded — a raw copy of the asset, a render that half-finished — an
# undefined function would be exit 127, and under `set -e` that KILLS the hook.
# A recorder that can kill the thing it observes is the one bug this partial may
# never have.
navori_audit_begin() { :; }
navori_audit_log() { :; }
# navori:include audit-log
navori_audit_begin

# The verdict is a VARIABLE resolved in a trap, not a call per branch. These
# hooks have several early exits each (no git, no worktrees, nothing to inject),
# and wiring a call into every one is how the set drifts the next time somebody
# adds an exit. Defaulting to `skip` makes a new early exit semantically correct
# for free: it means "ran, decided it had nothing to do", which is exactly what
# an unhandled early return is.
navori_audit_verdict="skip"
navori_audit_reason=""
navori_audit_on_exit() {
  navori_audit_log "$navori_audit_verdict" "$navori_audit_reason" || true
  return 0
}
trap navori_audit_on_exit EXIT


# Resolve the progress dirs. `placeHook` copies this body VERBATIM for every
# engine — it is never retargeted the way prose assets are (#389) — so the hook
# has to know every engine's path itself or it silently no-ops there: under
# Codex the handoff lives in `.codex/progress/` (what `compat.ts` rewrites
# `.claude/progress/` into), and this loop used to stop at two names it would
# never find. Bare `progress/` stays as the fallback for a repo that relocates
# it. (Literals, not interpolated: `progress.dir` isn't exposed to the render
# interpolator — same choice as session-start-context.sh.)
#
# EVERY existing dir is scanned, not the first one found: a repo that renders
# both engines has both, and picking one by probe order would make the hook
# blind to whichever engine happens to come second. An ARRAY, never an unquoted
# string: word-splitting a `$dirs` string is a no-op under zsh, which is how the
# receipt backstop silently stopped scanning (#344).
dirs=()
for d in ".claude/progress" ".codex/progress" "progress"; do
  [ -d "$d" ] && dirs+=("$d")
done
[ ${#dirs[@]} -gt 0 ] || exit 0

# Is a file empty or whitespace-only?
is_blank() { ! grep -q '[^[:space:]]' "$1" 2>/dev/null; }

problems=""
note() { problems="${problems}${problems:+; }$1"; }

# nullglob, so an absent report class yields zero iterations instead of a
# literal pattern (bash) or a hard "no matches found" abort (zsh, which also
# has no `shopt` — under `set -e` that unknown command killed the whole hook
# there, #391). Each shell spells the option its own way.
if [ -n "${ZSH_VERSION:-}" ]; then setopt NULL_GLOB; else shopt -s nullglob; fi
# Reports are named by their PATH, not their basename: with more than one
# progress dir in play, `impl_x.md` alone wouldn't say which one to open.
for dir in "${dirs[@]}"; do
  for f in "$dir"/impl_*.md; do
    if is_blank "$f"; then
      note "$f vacío"
    elif ! grep -qiE '^\*{0,2}status:?\*{0,2}' "$f" 2>/dev/null; then
      note "$f sin línea 'Status:'"
    fi
  done
  for f in "$dir"/review_*.md; do
    if is_blank "$f"; then
      note "$f vacío"
    elif ! grep -qE 'APPROVED|CHANGES_REQUESTED' "$f" 2>/dev/null; then
      note "$f sin veredicto (APPROVED/CHANGES_REQUESTED)"
    fi
  done
done

# `clean` vs `dirty` is the whole value of recording this hook: it is the only
# evidence that the handoff check RAN and found nothing, as opposed to never
# having run at all.
if [ -z "$problems" ]; then
  # Emptying the stamp is what keeps a RECURRENCE audible: the same problem
  # coming back after being fixed is news, and a stamp left behind would
  # swallow it. Truncated rather than deleted — one redirection, no process,
  # and no delete inside a hook that runs in the user's repo.
  : >"$navori_handoff_stamp" 2>/dev/null || true
  navori_audit_verdict="clean"
  exit 0
fi

# Same problem set as the previous firing of this session → the message was
# already delivered. The run is still RECORDED (verdict `repeat`), because "the
# check ran and found the same thing" is evidence the audit needs; what is
# skipped is only the injection.
#
# Read WITHOUT testing the path first, and that is deliberate: a failed
# redirection already answers "no stamp yet", and this script must keep having
# no existence test in it. `hook-claims-vs-scripts.test.ts` reads that absence
# as proof that the hook cannot notice a handoff that never landed — a `-f`
# here, on an unrelated file, would silently license every asset that claims it
# does.
navori_handoff_prev=""
IFS= read -r navori_handoff_prev <"$navori_handoff_stamp" 2>/dev/null || navori_handoff_prev=""
if [ "$navori_handoff_prev" = "$problems" ]; then
  navori_audit_verdict="repeat"
  navori_audit_reason="$problems"
  exit 0
fi
printf '%s\n' "$problems" >"$navori_handoff_stamp" 2>/dev/null || true

msg="navori: handoff(s) de subagente incompletos — ${problems}. Revisa que el reporte quedó bien escrito antes de consolidarlo."

if command -v node >/dev/null 2>&1; then
  MSG="$msg" node -e 'process.stdout.write(JSON.stringify({systemMessage:process.env.MSG}))'
elif command -v jq >/dev/null 2>&1; then
  jq -n --arg m "$msg" '{systemMessage:$m}'
fi
navori_audit_verdict="dirty"
navori_audit_reason="$problems"
exit 0
