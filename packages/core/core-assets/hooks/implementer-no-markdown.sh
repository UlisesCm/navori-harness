        # The shell closes at the FIRST exact delimiter line; anything after it is shell, not data.
        close = lines.index(heredoc.group(2))
        if lines[close + 1:] not in ([], [""]):
            fail()
        return "\n".join(lines[:close])
    invocation = re.fullmatch(r"[ \t]*python3[ \t]+-c[ \t]+(?:'([^']*)'|\"([^\"\\$`]*)\")[ \t]*", command, re.S)
    if invocation is None:
