#!/usr/bin/env bash
#
# Defensive PreToolUse(Bash) guard.
# Reads the full command (compound commands included) from Claude Code's tool
# input and HARD-BLOCKS (exit 2) the destructive patterns that static deny
# rules in settings.json can't reliably catch: variable-indirected `rm -rf`,
# force-push to the base branch, hook-skipping, fork bombs, and writes to block
# devices. Exit 2 in a PreToolUse hook is evaluated BEFORE permission rules, so
# this is the strongest line of defense — it overrides even an `allow` match.
#
# KNOWN, ACCEPTED LIMITATION: matching is regex-based over the command string —
# over the part of it the shell will actually INTERPRET, since #462 (see "INERT
# CONTENT" below: a heredoc body or a `-m`/`--body` value is data, not a call).
# A compound command is split into one segment per line first, so each rule only
# ever matches WITHIN a segment (see "SEGMENTS" below) — that is what keeps a
# `git commit` in one segment from being paired with a flag in another.
# Multi-line continuations, git global options (`git -C … commit`), and simple
# wrappers (`command`/`\git`/parens) ARE normalized before matching now, and a
# quoted skip-flag (`git commit "--no-verify"`) is still caught. Still unhandled:
# `sh -c`, `eval`, base64/printf obfuscation, and escaped-quote edge cases inside
# quoted spans. This guard is a SEATBELT against accidental
# destructive commands, NOT a sandbox against a deliberate adversary.
#
# The managed block below is regenerated by `navori render` and must NOT be
# edited by hand. Add your repo-specific guards in the user section at the
# bottom — `$cmd` is already parsed and in scope there.
# Blocking classification (#1117):
#   - every block() site: hard — it cannot inspect (ceilings), or the action is irreversible or a policy bypass.
#     Routes live in the message only where one exists: split the command (ceilings), commit without --no-verify,
#     feature branch / --force-with-lease (force-push), literal `rm -rf <absolute path>` (rm over a variable, which
#     the host asks the user to confirm). Root/home/system rm, --no-preserve-root, fork bomb and block devices
#     have no route. The tgrep search lane sub-block (guard-destructive-search-lane.sh) is hard as well.
#   - the Pi arm (rule 6c, spec 0048): hard — a write to the Pi control plane, `pi --no-extensions` and a
#     shared `deny` rule have no route; the control-plane write names `navori render --apply` as the way
#     Navori's own files change.
set -euo pipefail

# Command extraction (payload → $cmd). Shared body, single source of truth.
# A missing JSON parser used to make this guard wave every command through; the
# shared extractor falls back to sed so it still inspects the command.
# navori:include extract-cmd
cmd=$(extract_cmd)
# Spec 0035 D2: nv_project_dir is $CLAUDE_PROJECT_DIR under Claude (byte-
# identical to what this guard read before) and the git toplevel resolved
# from the payload's `cwd` under Codex — see the absolute-prefix arm below.
# navori:include hook-input

navori_audit_name="guard-destructive"
navori_audit_phase="PreToolUse"
navori_audit_tool="Bash"
# Fallback no-ops, overwritten by the real definitions the include brings in.
# They exist because this hook is FAIL-OPEN: if the file ever runs WITHOUT its
# includes expanded — a raw copy of the asset, a render that half-finished — an
# undefined function would be exit 127, and under `set -e` that KILLS the hook.
# A recorder that can kill the thing it observes is the one bug this partial may
# never have.
navori_audit_begin() { :; }
navori_audit_log() { :; }
# navori:include audit-repo
# navori:include audit-log
navori_audit_begin

# The verdict is resolved in a trap, NOT by a call at the end of the file.
#
# This hook's managed block ends before its `navori:user-section`, and the render
# only syncs what is INSIDE the block — so a call placed after it lives in the
# user's own territory and never reaches the mirror. That is exactly how the most
# critical hook in the harness ended up being the only one not recording.
#
# The trap also covers the extra guards a user writes in that section: whatever
# they add, the exit code still tells the truth about what happened.
navori_audit_verdict="allow"
navori_audit_reason=""
navori_audit_on_exit() {
  navori_audit_log "$navori_audit_verdict" "$navori_audit_reason" || true
  return 0
}
trap navori_audit_on_exit EXIT

if [ -z "$cmd" ]; then
  navori_audit_verdict="skip"
  navori_audit_reason="sin comando que inspeccionar"
  exit 0
fi

# branchBase is shell-quoted at render time via the shq: marker (#197): a
# hostile branchBase in navori.config.json lands here as an inert literal,
# never executable.
base={{shq:branchBase}}

# Spec 0048 D15: the shared `deny` permission rules, one `deny <token> ...` line each, rendered ONLY
# into the Pi copy (`extraVars.piPermissionRules`, from the same translation Codex's rules file
# uses). Every other copy carries `-`, and only the `pi` arm below ever reads it.
nv_pi_rules={{shq:piPermissionRules}}

block() {
  echo "[navori] BLOCKED by guard-destructive: $1" >&2
  # Truncated: the ceiling below blocks commands far larger than any transcript
  # should carry, and the reason line already says which rule fired.
  echo "[navori] command: ${cmd:0:2000}" >&2
  # $3: the route that gets the same intent through, when one exists. Rules
  # with no safe route (root delete, fork bomb, ...) pass none and say nothing.
  [ -z "${3:-}" ] || echo "[navori] route: $3" >&2
  # Only ASSIGNMENTS here: this is the one place the guard says no, and nothing
  # may come between the decision and `exit 2`. The recording happens in the
  # trap, after the exit is already committed.
  navori_audit_verdict="block"
  # $2: allowlisted audit reason code; user-section callers pass none.
  navori_audit_reason="${2:-unspecified}"
  exit 2
}

# BOUNDED WORK (#511) — the guard runs under a wall-clock timeout it does NOT
# control (10s, set by navori in build-settings.ts's GUARD_HOOK_DEST config —
# not a Claude Code default, which is 600s for command hooks), and being
# KILLED is indistinguishable from approving: the hook says nothing and the
# tool call proceeds. So a guard cannot defend itself by handling the
# timeout; it has to never get near it. Two halves, both load-bearing:
#
#   1. every pass below is LINEAR in what it reads — `sed`/`grep`, never a bash
#      `${var//pat/repl}` and never a bash string builder inside a loop. Both
#      are QUADRATIC in bash 3.2.57 (the /bin/bash macOS actually ships) and
#      both were here: one `${_split//&&/…}` over a 2000-segment command
#      measured 83s on its own, and the inert-content pass's per-line
#      `skeleton="${skeleton}${_line}"` measured 3.4s at 16k lines, 13.2s at
#      32k and 53.2s at 64k — 96-99% of the guard's whole runtime, and past the
#      timeout with not a single rule evaluated. The builder is an array append
#      plus one `printf` join now; the substitutions are `sed`.
#   2. what is still too big to inspect is DENIED, never waved through. A guard
#      that cannot evaluate a command must say no: the discarded input gets a
#      verdict, and that verdict is `block`. Nothing a human types reaches these
#      ceilings; what does is either generated or an attempt to drown the guard.
#
# The ceilings price the dimensions that actually cost, and they are SEPARATE
# because those dimensions cost differently. Conflating them is what the first
# cut of #511 got wrong: `CMD_MAX` bounded BYTES while the cost driver was LINES,
# so 16k one-char lines (3.4s, inside the ceiling) were admitted and a 40k-char
# prose heredoc (70ms, one pass) was denied — expensive work through, cheap work
# blocked, and the ~3x margin against the timeout there by accident.
# Every figure below is bash 3.2.57 on an M-series Mac, measured AT the ceiling:
#   · CMD_MAX  — total bytes. This prices the `sed`/`grep` passes, each of which
#     reads the whole command once, and they are cheap: one 131k-char line is
#     187ms, and the adversarial shape for the `rm` operand run (a single `rm`
#     segment filling the ceiling with operands) is 211ms — linear, no
#     backtracking blow-up.
#   · LINE_MAX — lines walked by the inert-content pass below, the only per-LINE
#     loop in this file, and one that runs at all ONLY when the command contains
#     `<<` (without one the skeleton IS the command). At the line ceiling with
#     every line KEPT (the expensive arm) and padded to the byte ceiling: 300ms.
#   · HEREDOC_PROBE_MAX — heredoc-opener candidates, each paying two `sed` and a
#     `grep` of its own on top of the per-line cost.
# All three at once — 64 openers, 4096 lines, 130k bytes — is 501ms, the worst
# case measured anywhere in this file. The audit's 2000-segment repro went from
# 46.9s (killed) to 65ms.
#
# The ceiling does NOT make the accumulator's shape a non-issue, which is why
# both halves ship: the quadratic builder at these very ceilings measures 3.5s
# against the array's 300ms — inside the 10s timeout on this machine, and past
# it on the 2-4x slower box the audit is actually worried about.
#
# NOT COVERED by a ceiling, deliberately: the line count of a command with NO
# `<<` in it. The per-line loop is skipped there, so what is left is linear in
# bytes and `CMD_MAX` prices it directly — the densest such input that fits,
# 64k one-char lines in 128k bytes, measures 442ms. It is named because the
# LINE_MAX row above would otherwise read as "lines are bounded", and they are
# only bounded on the path where they cost per line.
# Heredoc-body / `-m` value elision, `$live`, `$segments`: shared partial
# (`_partials/inert-skeleton.sh`, spec 0048 T12), also used by subagent-no-background.
# navori:include inert-skeleton
if [ "${#cmd}" -gt "$CMD_MAX" ]; then
  block "command too large to inspect (${#cmd} chars > ${CMD_MAX}) — nothing in it was evaluated" oversize "split it into smaller commands the guard can inspect."
fi

# `$skeleton` and the heredoc ceilings (LINE_MAX, HEREDOC_PROBE_MAX): the shared
# partial, called here so the fail-closed order is unchanged.
navori_inert_skeleton

# ─── Fast path: a command no rule below can possibly match ───────────────────
#
# WHY: this guard runs on EVERY Bash call, and in auto mode the host tells the
# agent to work through the shell — so it is in front of reads, greps and edits
# alike. Measured, it costs ~46 ms against a ~2 ms process floor: the other
# ~44 ms is the `sed`/`grep` pipeline below, roughly forty forks. Over one
# audited session that is 901 invocations and ~40 s of wall clock spent proving
# that `cat file` is not `rm -rf /`. On 9,398 real commands from that session,
# 80% contain none of the tokens below.
#
# WHY IT IS SOUND, which is the only part that matters in a security control:
# every `block` in this file needs one of these literal substrings to survive
# into the string its rule reads — `commit`/`push` (rules 1-2), `rm` (rule 3),
# `:(` (rule 4), `/dev/` (rule 5), `>`/`sed`/`tee` (rule 6, the three write
# verbs it recognizes), and `reset`/`clean`/`restore`/`checkout` (rule 7, whose
# regex ends in `(reset|checkout|restore|clean)` — one per git subcommand it
# inspects). No rule can fire without one.
#
# Rules 1-2 are keyed on `commit`/`push`, NOT on `git` (spec 0016 T3.1). Both go
# through `$git_cp`, whose regex ends in `(commit|push)` — and rule 2 narrows
# further to `push`. So `git` alone can never reach a `block`, and testing for it
# only made the fast path miss: `git` is the most frequent command family there
# is, and every `git status`, `git diff`, `git log` — plus every `cat
# .gitignore` and `ls .github/`, which merely CONTAIN the substring — paid the
# full ~46 ms to prove something the rules could not have found. Substring
# testing stays a superset of the regexes (any command `$git_cp` matches
# contains `commit` or `push` literally), so the argument above is unchanged;
# it just stopped being answered by a token four times too wide.
#
# The probe is the command with quotes, backslashes and newlines REMOVED, which
# is what makes the argument hold under the obfuscations the rules normalize
# away: `r'm' -rf ~` becomes `rm -rf ~`, `\git` becomes `git`, and a `g\<NL>it`
# split across a continuation is rejoined. Removal is the safe direction on
# purpose — none of the tokens contains a quote, a backslash or a newline, so
# stripping those can only CREATE matches, never destroy one. A false match
# costs the full analysis; a false miss would be a hole, and cannot happen here.
#
# PLACEMENT is load-bearing too: this sits AFTER the three fail-closed size
# limits (`CMD_MAX`, `LINE_MAX`, `HEREDOC_PROBE_MAX`) so a command too large to
# inspect is still blocked, exactly as before. It skips the rule machinery, never
# a refusal. And it reads `$cmd`, not `$skeleton`: the skeleton drops inert
# heredoc bodies, so scanning it would narrow what the probe sees.
#
# FAST_MAX exists because `${var//pat/}` is NOT linear in bash: on a string past
# ~64 KB with thousands of matches it goes superlinear hard — measured, 1024
# lines of quoted `echo` strip instantly and 2048 lines had not finished after
# nine minutes. An optimization that hangs the guard is a guard that hangs, so
# the probe is only built for a command small enough for the cost to be free.
# Above it, the full analysis runs exactly as it did before this block existed.
# 4096 covers 98.5% of 1,089 real commands from the measured session (p50 370,
# p90 1650) and sits sixteen times below the cliff.
FAST_MAX=4096
# The Pi arm (rule 6c below) adds its own literals: the control-plane paths (`.pi`), the `pi` word
# (`pi -ne`, `pi --no-extensions`) and the first token of every shared `deny` rule. Lowercased
# because the paths are matched case-insensitively (APFS); one `tr`, and only in a Pi copy.
nv_pi_candidate() {
  [ "$nv_engine" = pi ] || return 1
  local _lc _r _t
  _lc=$(printf '%s' "$_fast" | tr '[:upper:]' '[:lower:]')
  case "$_lc" in *.pi*|*extensions*|*"pi "*|*pi) return 0 ;; esac
  [ "$nv_pi_rules" != "-" ] || return 1
  while IFS= read -r _r; do
    _t=${_r#deny }
    _t=${_t%% *}
    [ -n "$_t" ] || continue
    case "$_lc" in *"$_t"*) return 0 ;; esac
  done <<< "$nv_pi_rules"
  return 1
}
if [ "${#cmd}" -le "$FAST_MAX" ]; then
  _fast=${cmd//\'/}
  _fast=${_fast//\"/}
  _fast=${_fast//\\/}
  _fast=${_fast//"${_nl}"/}
  case "$_fast" in
    *commit*|*push*|*rm*|*sed*|*tee*|*'/dev/'*|*'>'*|*':('*|*reset*|*clean*|*restore*|*checkout*) ;;
    # Search verbs: not destructive, but the user section below is where a plugin
    # lane (tgrep's search routing, spec 0039 D6) inspects them, and this early exit
    # would never let it run. `rg` needs a word edge: `*rg*` would match `merge`.
    *grep*|*rg\ *|*rg) ;;
    *)
      if ! nv_pi_candidate; then
        navori_audit_verdict="skip"
        navori_audit_reason="no rule token in the command"
        exit 0
      fi
      ;;
  esac
fi

navori_inert_live

navori_inert_segments

# Same list with quoted spans dropped, used ONLY by the combined-short-flag
# check, so a hyphen-word inside a commit message (`-m "add -notify option"`)
# can't trip it.
segments_unquoted=$(printf '%s' "$segments" | sed -E -e "s/'[^']*'//g" -e "s/\"[^\"]*\"//g")

# Git commit/push detector shared by rule 1. The leading boundary accepts ; & |
# so `true;git commit …` (no space after the separator) is caught; the
# `git(… -opt …)*` middle allows git global options between `git` and the
# subcommand (`git -c k=v commit …`).
git_cp='(^|[[:space:]]|[;&|])git([[:space:]]+-[a-zA-Z-]+(=[^[:space:]]+)?([[:space:]]+[^-][^[:space:]]*)?)*[[:space:]]+(commit|push)'

# 1. Skipping quality gates / hooks — defeats the whole point of the harness.
#    Two checks: the literal `--no-verify` over `segments` (quotes kept, so a
#    quoted flag is still caught), and `-[a-zA-Z]*n[a-zA-Z]*` over
#    `segments_unquoted` to catch `-n` folded into a combined short-flag token
#    (`git commit -qn`/`-nq`) without a hyphen-word in a message tripping it.
#    Both run over the SEGMENT list, so the `.*` between the git invocation and
#    the flag can never leave the segment that holds the commit/push. Matching
#    the whole command string instead is what made `git commit -m x && git log
#    -n 3` (or `&& grep -rn TODO src/`) block as a bogus "--no-verify": any short
#    flag carrying an `n` ANYWHERE later in the line was read as the commit's.
if printf '%s' "$segments"            | grep -qE "${git_cp}.*--no-verify" \
  || printf '%s' "$segments_unquoted" | grep -qE "${git_cp}.*[[:space:]]-[a-zA-Z]*n[a-zA-Z]*([[:space:]]|\$)"; then
  block "git commit/push with --no-verify (skipping hooks/gates)" no-verify "commit without --no-verify and fix what the hook reports."
fi

# 2. Force-push to the base branch. force-with-lease is allowed (safe rebase
#    flow on feature branches); bare --force/-f against the base branch is not.
#    #307: every sub-check is scoped to the ACTUAL `git push` invocation(s),
#    never the whole command string. Keeping only the segments that START a
#    `git … push` means a `+`
#    in a commit message (`-m "format:check + test"`), a base-branch name in a
#    sibling command (`gh pr create --base main`), or a heredoc/`--body` can no
#    longer be misread as a force-push refspec or as the pushed ref — that
#    false positive blocked legit compound commit+push+PR commands. The refspec
#    `+` is matched only when glued to a ref (`+main`, never `+ test`), the way
#    git actually spells a force-push refspec.
push_seg=$(printf '%s' "$segments" \
  | grep -E '^git([[:space:]]+-[a-zA-Z-]+(=[^[:space:]]+)?([[:space:]]+[^-][^[:space:]]*)?)*[[:space:]]+push([[:space:]]|$)' \
  || true)

if [ -n "$push_seg" ] \
  && printf '%s' "$push_seg" | grep -qE '(--force([[:space:]]|$)|[[:space:]]-f([[:space:]]|$)|[[:space:]]\+[^[:space:]])' \
  && ! printf '%s' "$push_seg" | grep -qE 'force-with-lease' \
  && printf '%s' "$push_seg" | grep -qE "(^|[[:space:]+/])${base}([[:space:]]|\$)"; then
  block "force-push to the base branch '${base}'" force-push-base "push a feature branch, or use --force-with-lease on it."
fi

# 3. rm -rf with variable indirection or absolute home/system roots that static
#    deny globs miss. The deny rules in settings.json (`Bash(rm -rf ~/*)`,
#    `Bash(rm -rf /*)`) only match a command that STARTS that way, so anything
#    compound (`cd /tmp && rm -rf ~/`) walks past them — exactly the class this
#    guard exists to cover. Matching per SEGMENT is what makes that work: `$`
#    below means "end of this segment", so the target no longer has to sit at
#    the end of the whole command line.
#
#    COVERED (blocked). The FLAGS axis is normalized (see below), so every
#    spelling of "recursive/force" counts: `-rf`, `-fr`, `-r`, `-R`, `-fR`,
#    `--recursive`, `--force`, and any mix of them, with other option tokens
#    (`--no-preserve-root`, `--one-file-system`, a `--` separator) interleaved.
#    The OPERAND axis is scanned whole (see below): `rm` takes a LIST of paths,
#    so a sensitive one blocks wherever it sits in that list.
#    The QUOTING axis counts too: a quote AROUND the target — opening, closing,
#    single or double — is stripped by the shell before `rm` ever sees the path,
#    so `rm -rf "/"` deletes exactly what `rm -rf /` deletes and the two must get
#    the same verdict. They did not: the rule accepted an opening quote and had
#    no ending for the closing one, so `"/"`, `'/'`, `"/usr"`, `"~"` and
#    `rm -rf build "/etc"` all returned 0. Worse than the hole was its SHAPE —
#    `rm -rf "~/"` did block, by accident (the home pattern's path-component
#    class swallowed the closing quote as if it were part of the path), so a
#    spot-check on the obvious spelling reported the axis as covered.
#    The rows below name one spelling each; the TARGET is what they vary:
#      rm -rf $VAR / "$VAR"        variable indirection (`PATH=/; rm -rf $PATH`)
#      rm -rf /   ·  rm -rf /*     the filesystem root
#      rm -rf ~   ·  ~/  ·  ~/Documents        HOME and its immediate children
#      rm -rf /Users/me  ·  /Users/me/Desktop  the same, spelled absolutely
#      rm -rf /usr  ·  /etc  ·  /var/folders   a system root or an immediate child
#      rm -rf /tmp  ·  /private/tmp            the scratch root itself, bare
#      rm -rf "/" · '/' · "/usr" · "~" · build "/etc"   any of the above QUOTED
#    NOT COVERED (deliberate, so everyday cleanup keeps working):
#      relative paths — `rm -rf node_modules`, `rm -rf ./dist`
#      anything INSIDE the scratch root — `rm -rf /tmp/navori-test-123`: a temp
#        dir is scratch by definition and agents create and delete them all day;
#        only wiping `/tmp` wholesale is the accident worth catching.
#      DEEP absolute paths — `rm -rf /Users/me/dev/app/node_modules`, `/tmp/x/y`:
#        past the first level under a root, a path is assumed to be project or
#        scratch data. Wiping HOME or a system dir is the accident worth
#        catching; a deep path is a targeted delete, and blocking every one of
#        them would fire daily (agents are told to use absolute paths) and only
#        teach the operator to route around the guard.
#      quoting SPLICED INTO the path, and backslash escapes — `rm -rf /"u"sr`,
#        `rm -rf "/us"r`, `rm -rf \~`, `rm -rf \/`. The shell removes those
#        before `rm` runs, so they name the same paths the rows above cover; the
#        guard reads TEXT and the pattern needs the path spelled contiguously.
#        This is the residue of the quoting axis, and it is named because the
#        row above claims that axis: quotes AROUND the target are covered,
#        quotes INSIDE it are not. Same class as the escaped-word limitation the
#        header already states (`b\ash f`), and it needs a deliberate hand —
#        nobody types `/"u"sr` by accident.
#      `sh -c`, `eval`, base64/printf obfuscation — seatbelt, not a sandbox.
#
#    FLAG NORMALIZATION (#509). The rule used to describe the danger by the
#    TEXT it usually wears (`-[a-zA-Z]*[rf]…`, lowercase) instead of by what
#    `rm` MEANS, so three everyday spellings of the same command walked past it:
#    `rm -R ~/` (POSIX/GNU/BSD all treat `-R` as `-r`), `rm --recursive --force
#    ~/`, and `rm -rf --no-preserve-root /` — the one command that erases the
#    system root, and the only one of the three that also evades the static
#    `deny` globs. So the flags are NORMALIZED before they are matched:
#      · long → short: `--recursive`→`-r`, `--force`→`-f`, `--dir`→`-d`.
#        Rewritten (not just alternated into the pattern) because a long flag
#        sits between `rm` and its target and otherwise breaks the run.
#      · `-R` ≡ `-r` lives in the character class instead: BSD `sed` has no
#        portable case-folding (`\l`/`\U` are GNU-only), and folding the whole
#        segment would corrupt the TARGET, which is case-sensitive.
#      · any other option token is allowed to sit anywhere in the run, so
#        `--no-preserve-root`, `--one-file-system` or a `--` separator no longer
#        detach the recursive flag from its target.
#    `segments_rm` is read by THIS rule only — rewriting `--force` globally
#    would otherwise reach the force-push rule.
#
#    EVERY OPERAND, NOT JUST THE FIRST. The same defect one axis over: the rule
#    matched `rm`, then the flags, then ONE target, so a harmless path in first
#    position detached the rule from everything after it — `rm -rf build /` and
#    `rm -rf node_modules ~/` both erased the root/HOME with exit 0. But `rm`
#    takes a LIST of operands and deletes every one of them, so sensitivity is a
#    property of the TARGET's shape (root / home / variable), never of its
#    position. `rm_arg` is therefore a run of ANY argument tokens — further
#    options and harmless operands alike — between the recursive flag and the
#    target, and the same run is allowed BEFORE the flag so that GNU's option
#    permutation (`rm build -rf /`, which really does erase `/` on Linux) is
#    covered too. False positives stay bounded because the verdict still hangs
#    on the target: `rm -rf build coverage` has no sensitive operand and keeps
#    passing, exactly as the verdict table demands.
#    `rm_arg` excludes `<`, `>` and `&` on purpose — what follows a redirection
#    or a `&` is not something `rm` deletes, so `rm -rf dist > /dev/null` (or
#    `rm dist & ls -R /usr`) must not be read as `rm -rf /dev/null`.
#
#    THE FALSE POSITIVE THIS BUYS, named rather than left to be discovered.
#    "Any token" also means tokens that are not operands of that `rm` at all, so
#    an UNQUOTED mention of `rm` anywhere in a segment now reaches forward to any
#    sensitive absolute path later in the SAME segment. Measured, all exit 2:
#      echo rm -rf build /usr
#      python3 -c "print(1)" # rm -rf a /bin/zsh      ← inside a comment
#      rm -rf "release /usr notes"                     ← one quoted operand
#    It is a deliberate trade, and a bounded one: the mention has to be
#    unquoted (a `-m "…rm -rf ~/…"` message or a heredoc body was already elided
#    into `live`, and `(^|[[:space:]])rm` does not match after a `"`), it has to
#    share a segment with the path (`;`, `&&`, `||`, `|` all end the reach), and
#    the path still has to be root/home/system — `echo rm -rf build dist` passes.
#    The everyday shapes that LOOK like this stay clean, and the verdict tables
#    pin them: `find … -exec rm -rf {} +`, `xargs rm -rf`, `rm -rf dist >
#    /dev/null`, `docker run --rm -v /var/run/docker.sock:…`, `tar -rf a.tar
#    /etc/hosts`, `cp -R /usr/share/x .`. Narrowing `rm_arg` to "options only"
#    is what reopens `rm -rf build /`, and an erased root costs more than a
#    blocked `echo`; the header's seatbelt framing is the standing answer, and
#    the way past a firing here is to quote the mention or split the segment.
segments_rm=$(printf '%s' "$segments" | sed -E \
  -e 's/(^|[[:space:]])--recursive([[:space:]]|$)/\1-r\2/g' \
  -e 's/(^|[[:space:]])--force([[:space:]]|$)/\1-f\2/g' \
  -e 's/(^|[[:space:]])--dir([[:space:]]|$)/\1-d\2/g')
#    `git rm --cached` is not a deletion (#655). It rewrites the INDEX and leaves
#    the file on disk — and it is the exact fix `doctor` prescribes for an
#    ephemeral that stayed tracked (#646), so the harness was blocking its own
#    advice the moment the path came from a variable. The `rm` VERB is renamed in
#    that ONE shape so `rm_run` stops seeing it; nothing else about the segment
#    changes.
#
#    Why not anchor `rm` to the start of the segment instead, which is the
#    tempting general fix: `xargs rm -rf /usr` and `find … -exec rm -rf {} +` put
#    the verb mid-segment and are genuinely destructive, so anchoring would let
#    them through. The verb has to stay reachable mid-segment; only this one
#    non-deleting spelling gets exempted.
#
#    It cannot be used to disarm a real deletion. The rewrite needs `git` before
#    the verb AND `--cached` in the SAME segment, and segments split on `;`,
#    `&&`, `||` and `|` — so a real recursive delete chained after a `git rm
#    --cached` still blocks on its own segment, and one that merely trails a
#    `--cached` token has no `git` and is untouched. Both are pinned in the
#    verdict table.
#
#    `_git_opt` lets git's own global options sit between the wrapper and the
#    verb, values included (`git -c k=v rm --cached`). That token run is the
#    widest part of the exemption and stays bounded by the three conditions
#    above: a segment beginning with `git` cannot hold a second command, and no
#    single `git` invocation deletes outside the repo.
_git_opt='-[^[:space:]]+[[:space:]]+([^-][^[:space:]]*[[:space:]]+)?'
segments_rm=$(printf '%s' "$segments_rm" | sed -E \
  -e "/--cached/ s/(^|[[:space:]])git([[:space:]]+(${_git_opt})*)rm([[:space:]])/\1git\2git-rm\4/g")
rm_arg='[^<>&[:space:]]+[[:space:]]+'           # any option OR operand token
rm_kill='-[a-zA-Z]*[rRf][a-zA-Z]*[[:space:]]+'  # a short option carrying r/R/f
rm_run="(^|[[:space:]])rm[[:space:]]+(${rm_arg})*${rm_kill}(${rm_arg})*"
rm_quote="[\"']?"                     # ONE optional quote, either flavour
rm_var='\$'                           # `$VAR`, `${VAR}` — any variable
rm_home='~(/[^[:space:]/]*)?|/(Users|home)(/[^[:space:]/]+(/[^[:space:]/]*)?)?'
rm_root='/\*?|/(Applications|Library|System|Volumes|bin|boot|dev|etc|lib|lib64|mnt|opt|root|sbin|srv|sys|usr|var)(/[^[:space:]/]*)?'
rm_tmp='/private(/tmp)?|/tmp'         # scratch root: the root itself, never a child
# The CLOSING quote is part of the ending, not an afterthought: without it the
# rule read `rm -rf "/"` as "root, then a character that is not the end of the
# segment" and returned 0. `rm_quote` appears on BOTH sides of the target below.
rm_end="/?${rm_quote}([[:space:]]|\$)"  # optional trailing `/`, closing quote, end
#    A VARIABLE target blocks only with a RECURSIVE flag (spec 0039 R23/R24): a
#    plain `rm -f "$TMPDIR/x"` deletes one file and is everyday cleanup, while
#    `rm -rf "$X"` can erase a tree. `rm_rec` is `rm_kill` narrowed to r/R (the
#    long `--recursive` was already rewritten to `-r`, combined `-rf`/`-fr` match
#    the class). Root, home and tmp keep the broader r/R/f flag run, unchanged.
rm_rec='-[a-zA-Z]*[rR][a-zA-Z]*[[:space:]]+'
rm_run_rec="(^|[[:space:]])rm[[:space:]]+(${rm_arg})*${rm_rec}(${rm_arg})*"
# GNU `rm` also accepts options AFTER the operands, so the recursive flag may
# follow the variable (`rm -f $X -r`, `rm $X -rf`). `--` is not special-cased:
# a `-r` token after it is treated as recursive too, the safe side (`rm -f --
# -r $X` blocks, as it did before).
rm_run_post="(^|[[:space:]])rm[[:space:]]+(${rm_arg})*${rm_quote}${rm_var}[^<>&[:space:]]*[[:space:]]+(${rm_arg})*-[a-zA-Z]*[rR][a-zA-Z]*([[:space:]]|\$)"
# Split in two (#1117) so each block carries the message it deserves: a root /
# home / system / scratch-root target has NO safe route; a variable target does.
if printf '%s' "$segments_rm" \
  | grep -qE "${rm_run}${rm_quote}((${rm_home}|${rm_root}|${rm_tmp})${rm_end})"; then
  block "recursive rm over root / home / system / scratch root" rm-root
fi
if printf '%s' "$segments_rm" \
  | grep -qE "${rm_run_rec}${rm_quote}${rm_var}" \
  || printf '%s' "$segments_rm" \
  | grep -qE "${rm_run_post}"; then
  block "recursive rm over a variable" rm-var \
    "the variable cannot be inspected; resolve it first and re-issue the delete as 'rm -rf <absolute path>' with the literal absolute path — the host then asks the user to confirm that exact command."
fi

# 3b. `--no-preserve-root` is an aggravating factor on its own (#509): it exists
#     for the single purpose of disarming the last safety net `rm` has, and no
#     legitimate use of it exists inside an agent. Target, flag order and
#     quoting are therefore irrelevant — its presence in an `rm` SEGMENT blocks.
#     "Quoting is irrelevant" is now true rather than asserted: the flag carries
#     the same `rm_quote` on both sides that rule 3's target does, so
#     `rm "--no-preserve-root" -rf ./build` blocks like the bare spelling. It
#     read as covered before and was not — the same shape as the target-side
#     hole, one rule over.
#     Scoped to the segment (grep is line-based) so an `rm` in one command and
#     the flag in another are never paired; a commit message or a heredoc body
#     that merely quotes it was already elided into `live` and never gets here.
if printf '%s' "$segments" \
  | grep -qE "(^|[[:space:]])rm[[:space:]](.*[[:space:]])?${rm_quote}--no-preserve-root${rm_quote}([[:space:]]|\$)"; then
  block "rm --no-preserve-root (disarms rm's own root protection)" no-preserve-root
fi

# 4. Fork bomb. Reads `live`, not `scan`: FIX C turns `(` into a space, which
#    would defuse the very pattern this rule looks for.
if printf '%s' "$live" | grep -qE ':\(\)[[:space:]]*\{[[:space:]]*:\|:'; then
  block "fork bomb" fork-bomb
fi

# 5. Writing to a raw block device (wipes a disk/partition).
if printf '%s' "$live" | grep -qE '(of=/dev/(sd|nvme|disk|hd)|>[[:space:]]*/dev/(sd|nvme|disk|hd))'; then
  block "direct write to a block device" block-device
fi

# 6. Shell rewrites of a file navori MAINTAINS (#530). In auto mode every edit
#    arrives as a shell command — `sed -i`, a heredoc, a `>` redirect — instead
#    of the `Edit` tool, and the two fail very differently: `Edit` aborts when
#    the old text doesn't match (a check that the agent understood the file),
#    while `sed -i` with a pattern that matches nothing exits 0 and a `>` with
#    the wrong path truncates the file. On a managed file the damage is the #523
#    shape: the body changes, its `hash=` no longer matches, navori marks the
#    block `user-modified` and STOPS UPDATING IT. Nothing announces that.
#
#    These files are a MIRROR, and the harness already says so in prose ("los
#    conflictos en `.claude/` y CLAUDE.md no se resuelven a mano: son espejo").
#    This rule is that policy made executable. The way to change them is to edit
#    the source asset and run `navori render --apply`, or `navori sync` to
#    reconcile — neither of which matches here, because neither redirects.
#
#    COVERED (blocked), by FORM of the write:
#      > path  ·  >| path        truncating redirect (`>>` append is NOT: it adds
#                                after the blocks and invalidates no hash)
#      sed -i … path             in-place rewrite
#      tee path                  overwrite (`tee -a` is an append, so it is not)
#    …and by TARGET, the marker-carrying outputs of `ENGINE_OUTPUTS`
#    (lib/health.ts), which is what "managed" means anywhere else in navori:
#      CLAUDE.md · AGENTS.md · .claude/settings.json
#      .claude/agents · .claude/skills · .claude/hooks
#      .agents/skills · .codex/config.toml · .codex/agents · .codex/hooks
#      .cursor/rules
#
#    NOT COVERED, and each exclusion is load-bearing:
#      .claude/progress/… and .codex/progress/…   the agent handoff files, for
#        BOTH engines. Every subagent ends by writing one, usually with a
#        heredoc; blocking that breaks the harness's own protocol with the
#        harness's own guard. They carry no markers, so nothing there can be
#        invalidated. Naming `.codex/` wholesale was exactly that bug: it
#        swallowed `.codex/progress/` and would have silenced every Codex
#        subagent's handoff (#389's rule caught it).
#      .claude/settings.local.json · .claude/worktrees/   machine-local, never
#        rendered, never marker-managed.
#      cp/mv INTO a managed path, `python -c` writes, `awk > file`, `perl -i`.
#        Enumerating write verbs is the losing half of this fight — the same
#        "describe the danger by its textual form" pattern the blind audit found
#        eight times. The PostToolUse watcher is the half that doesn't care about
#        form: it re-checks the hashes AFTER the fact, so anything that gets past
#        this rule still surfaces. This rule is the seatbelt; that one is the net.
managed_dir='\.claude/(agents|skills|hooks)|\.agents/skills|\.codex/(agents|hooks)|\.cursor/rules'
# Spec 0048 D4 (R3): in a Pi copy only, the exact names Navori writes under `.pi/`: its extension,
# manifest, hook copies and the role files of its roster. A `.pi/agents/<other>.md` is the user's.
# Empty everywhere else, so the Claude and Codex regex is the one it always was.
managed_pi=''
if [ "$nv_engine" = pi ]; then
  managed_pi='|\.pi/extensions/navori\.ts|\.pi/navori\.json|\.pi/navori/[^[:space:];&|]+|\.pi/agents/(scout|implementer|reviewer|scribe|auditor|architect|publisher)\.md'
fi
managed_path="(CLAUDE\.md|AGENTS\.md|\.claude/settings\.json|\.codex/config\.toml|(${managed_dir})/[^[:space:];&|]+${managed_pi})"
managed_rewrite_msg="shell rewrite of a navori-managed file — edit the source asset and run 'navori render --apply' (or 'navori sync'); a direct write invalidates the block hash and freezes it. If the target is outside this project (e.g. a scratchpad), write it with '>' or 'tee' and an absolute path instead"
# The redirect check reads `scan`, NOT `segments`: the split rewrites every `|`
# into a newline, so `>| CLAUDE.md` (forced clobber) would be torn in half and
# the target would land in a segment of its own. Reading the unsplit copy is
# safe HERE and nowhere else in this file, because the pattern is local — only
# whitespace may sit between the `>` and its target, so it cannot reach across a
# `&&` into another command the way rules 1-3 could.
# `-[a-zA-Z]*i[a-zA-Z]*[^[:space:]]*` accepts the backup-suffix spellings that
# are the everyday form on both platforms: GNU `sed -i.bak`, BSD `sed -i ''`.
# Missing them would have left the rule covering the tutorial spelling only.
# Case-INSENSITIVE (`-i`), same reasoning as the heredoc script-extension check
# above (~line 319): APFS is case-insensitive by default, so `> .CLAUDE/AGENTS/a.md`
# writes the same file as `.claude/agents/a.md` and must not slip past a
# case-sensitive match.
if printf '%s' "$scan" | grep -qiE "(^|[^>])>\|?[[:space:]]*(\./)?${managed_path}([[:space:]]|\$)" \
  || printf '%s' "$segments" | grep -qiE "(^|[[:space:]])sed[[:space:]]+(-[a-zA-Z]*i[a-zA-Z]*[^[:space:]]*|--in-place)([[:space:]]|=).*${managed_path}" \
  || printf '%s' "$segments" | grep -qiE "(^|[[:space:]])tee[[:space:]]+([^-][^[:space:]]*[[:space:]]+)*(\./)?${managed_path}([[:space:]]|\$)"; then
  block "$managed_rewrite_msg" managed-rewrite
fi

# 6b (#1034). The `>`/`>|`/`tee` arms above only ever match a BARE or
# `./`-relative managed path, by design — `sed -i`'s own arm is unanchored
# (`.*managed_path`) so it already catches an absolute target as a side effect,
# but `>`/`tee` never reach `managed_path` at all for an absolute one, in or out
# of the project (confirmed empirically, challenge_1027.md CONCERN 1). #1027
# proposed closing that by RESOLVING the target against the filesystem at
# check-time (`cd -P`, symlink checks) to decide "inside vs outside" — rejected
# (challenge_1027.md BLOCKER 1): an ordinary `rm <target> && ln -s <managed
# file> <target> && tee <target>` in the SAME command swaps what the literal
# path resolves to between the check and the write, so a filesystem check is
# TOCTOU-defeated by construction, not by an adversarial trick.
#
# What stays textual and TOCTOU-proof: matching an absolute target whose
# CHARACTERS start with this project's own path — no `cd`, no `pwd -P`, no
# `[ -L ]`, so there is nothing for a same-command `rm`/`ln -s` to invalidate.
# Two forms reach that:
#   - the RESOLVED value of $CLAUDE_PROJECT_DIR, regex-escaped so a literal
#     char in the path (this repo's own path has a space and a hyphen, "Dev -
#     Docs") is never read as a metacharacter;
#   - the UNRESOLVED variable text itself, `$CLAUDE_PROJECT_DIR` /
#     `${CLAUDE_PROJECT_DIR}`, which an agent can compose into a redirect
#     without ever expanding it (so this arm doesn't depend on the value).
# Quoted and unquoted forms both matter, and NOT just as "the whole target is
# quoted or it isn't": `"$CLAUDE_PROJECT_DIR"/CLAUDE.md` — quoting only the
# variable expansion, then continuing unquoted — is ordinary POSIX style a
# legitimate command uses unprompted, so the quote has to be optional AROUND
# THE PREFIX TOKEN ITSELF (both the literal value and the `$VAR`/`${VAR}` text),
# not only at the two ends of the whole match (#1034 round 2 review). A path
# with a space in it (like this repo's) also HAS to be quoted somewhere to be
# valid shell at all, so this isn't a cosmetic tolerance.
# Absolute paths OUTSIDE the project (any other prefix) stay allowed on
# purpose — the block message above offers exactly that escape (#1036), and a
# sibling directory that merely shares the prefix (`<proj>-otro/CLAUDE.md`)
# does not match either: the pattern requires a literal `/` (optionally
# quoted) right after the project path, and a sibling has `-otro/…` there
# instead.
# Without a project dir resolved, this arm is skipped entirely — same
# behavior as before #1034 — rather than matching against an empty prefix.
# Spec 0035 D2: `nv_project_dir` is `$CLAUDE_PROJECT_DIR` under Claude (same
# value, same guard as before) and the payload's `cwd` resolved to its git
# toplevel under Codex, so the SAME absolute-prefix protection now covers
# both engines instead of only firing when Claude's env var happens to be set.
if [ -n "${nv_project_dir:-}" ]; then
  # Strip a trailing slash before escaping: a trailing `/` would otherwise
  # need a doubled `//` to line up with `/${managed_path}` below and silently
  # stop matching (round 2 review, informational note 1).
  cpd_literal=$(printf '%s' "${nv_project_dir%/}" | sed -E 's#[^a-zA-Z0-9_/ -]#\\&#g')
  if [ "$nv_engine" = codex ]; then
    # The UNRESOLVED command substitution text itself — the exact form
    # `.codex/config.toml` uses for every hook command (build-config-toml.ts)
    # — which an agent can compose into a redirect without ever expanding it.
    unresolved_prefix='\$\(git rev-parse --show-toplevel\)'
  else
    unresolved_prefix='\$\{?CLAUDE_PROJECT_DIR\}?'
  fi
  abs_managed_path="[\"']?(${cpd_literal}|${unresolved_prefix})[\"']?/${managed_path}[\"']?"
  if printf '%s' "$scan" | grep -qiE "(^|[^>])>\|?[[:space:]]*${abs_managed_path}([[:space:]]|\$)" \
    || printf '%s' "$segments" | grep -qiE "(^|[[:space:]])tee[[:space:]]+([^-][^[:space:]]*[[:space:]]+)*${abs_managed_path}([[:space:]]|\$)"; then
    block "$managed_rewrite_msg" managed-rewrite
  fi
fi

# 6c. The Pi arm (spec 0048 D4/D15, R2/R18) — three rules that exist only in a Pi copy, because only
#     Pi has no host permission system and runs this script from `.pi/navori/hooks/`. In a Claude or
#     Codex copy this whole block is skipped.
#
#     (i) CONTROL PLANE. `.pi/navori/**` (hook copies, the bridge's own scripts), `.pi/extensions/**`
#     (the extension that enforces all of this, and anything else Pi loads), `.pi/settings.json` and
#     `.pi/navori.json` decide whether and how the guards run, so an agent that can rewrite them can
#     switch the guards off. They are protected against every WRITE verb — `>`/`>>`/`>|`, `tee`,
#     `sed -i`, `rm`, `mv`, `cp`, `ln`, `dd`, `install`, `truncate`, `chmod`, `git checkout|restore`
#     and the like — and against INLINE interpreters (`python -c`, `node -e`, `perl -i`, `ruby -e`,
#     `php -r`) that name them. Reading them (`cat`, `ls`, `grep`) stays free. `cp`/`mv` match either
#     operand (a read-copy out of the plane is blocked too): the safe side of not parsing operands.
#     The match is on the path TEXT, case-insensitively: `./.pi/...`, `/abs/proj/.pi/...` and
#     `"$PWD"/.pi/...` all contain `.pi/<name>`. Still unhandled, by the header's seatbelt rule: a
#     `cd .pi/navori` followed by a relative write, a path assembled from variables, `sh -c` and
#     `eval`. The message names `navori render --apply` for the files Navori generates and says the
#     rest is edited by the user, outside the agent.
#
#     (ii) `pi --no-extensions` (or `-ne`) from bash starts a Pi with none of this loaded: no guard,
#     no bridge. Blocked, no route.
#
#     (iii) DENY RULES. The shared `deny` permissions, translated to token prefixes at render time
#     (`nv_pi_rules`, the same translation as `.codex/rules/navori.rules`), are compared with each
#     SEGMENT, quotes dropped and blanks squeezed: `sudo rm -rf x` and `mkfs /dev/sda` block, in
#     a compound command too. `mkfs.ext4 /dev/sda` does NOT: only the exact `mkfs` token matches
#     (same as Codex, codex-parity F9). A `*` glued to the last token was narrowed to the exact token (as in
#     Codex), so `rm -rf /` blocks and `rm -rf /tmp/x` does not — the numbered rules above catch the
#     variants. `ask` rules are not evaluated here (spec 0048 T11).
if [ "$nv_engine" = pi ]; then
  _q="[\"']"
  pi_cp="\.pi/(navori(\.json|/[^[:space:];&|<>\"']*)?|extensions(/[^[:space:];&|<>\"']*)?|settings\.json)"
  pi_cp_end="([[:space:]\"';&|)<>]|\$)"
  pi_cp_msg="shell write to the Pi control plane (.pi/navori, .pi/extensions, .pi/settings.json, .pi/navori.json) — these files decide whether the guards run. Navori's own are regenerated by 'navori render --apply' (or 'navori sync'); any other change is for the user to make outside the agent"
  _pi_cp_segs=$(printf '%s' "$segments" | grep -iE "${pi_cp}${pi_cp_end}" || true)
  pi_cp_verbs="(^|[[:space:]\"'])(rm|rmdir|unlink|mv|cp|ln|dd|install|truncate|chmod|chown|rsync|tee|touch|mkdir)[[:space:]]"
  pi_cp_sed="(^|[[:space:]\"'])sed[[:space:]]+(-[a-zA-Z]*i[a-zA-Z]*[^[:space:]]*|--in-place)([[:space:]]|=)"
  pi_cp_git="^git[[:space:]]+(.*[[:space:]])?(checkout|restore)[[:space:]]"
  pi_cp_interp="(^|[[:space:]\"'])(python[0-9.]*|node(js)?|deno|bun|perl|ruby|php|osascript)[[:space:]]+(.*[[:space:]])?(-[a-zA-Z]*[cepir][a-zA-Z]*|--eval|--print)([[:space:]=]|\$)"
  if { [ -n "$_pi_cp_segs" ] && {
         printf '%s' "$_pi_cp_segs" | grep -qiE "${pi_cp_verbs}" \
         || printf '%s' "$_pi_cp_segs" | grep -qiE "${pi_cp_sed}" \
         || printf '%s' "$_pi_cp_segs" | grep -qiE "${pi_cp_git}" \
         || printf '%s' "$_pi_cp_segs" | grep -qiE "${pi_cp_interp}"; } ; } \
    || printf '%s' "$scan" | grep -qiE ">[>|]?[[:space:]]*${_q}?([^[:space:];&|<>]*/)?${pi_cp}${pi_cp_end}"; then
    block "$pi_cp_msg" managed-rewrite "navori render --apply"
  fi
  if printf '%s' "$segments" | grep -qE "(^|[[:space:]\"'/])pi[[:space:]]+(.*[[:space:]])?(--no-extensions|-ne)([[:space:]=]|\$)"; then
    block "pi --no-extensions starts an agent without Navori's guards (no extension, no bridge, no hooks)" unspecified
  fi
  if [ "$nv_pi_rules" != "-" ]; then
    _pr_segs=$(printf '%s' "$segments" | tr -d "'\"" | tr -s '[:blank:]' ' ')
    while IFS= read -r _seg; do
      _seg=${_seg# }
      _seg=${_seg% }
      [ -n "$_seg" ] || continue
      while IFS= read -r _rule; do
        case "$_rule" in 'deny '*) ;; *) continue ;; esac
        _pfx=${_rule#deny }
        case "$_seg" in
          "$_pfx" | "$_pfx "*)
            block "shared permission deny rule '${_pfx}' (the same rule that denies it in Claude and Codex)" unspecified
            ;;
        esac
      done <<< "$nv_pi_rules"
    done <<< "$_pr_segs"
  fi
fi

# 7. Whole-tree discards of work that exists only in the working tree (#1252).
#    A subagent that committed the wrong diff recovered with `git reset --hard`
#    and erased reviewed, uncommitted work: unlike every rule above, the damage
#    here depends on STATE, not on text — the same command is a harmless no-op on
#    a clean tree and an irreversible loss on a dirty one. So the verdict asks
#    the repository, and blocks only when there is something to lose.
#
#    COVERED (blocked when the target repo has what the command would destroy):
#      git reset --hard · git checkout -f · git checkout -- . / git checkout .
#      git restore <paths>   without --staged (or with --staged --worktree)
#        → destroyed = tracked changes: `git status --porcelain --untracked-files=no`
#      git clean -f…         (-fd, -fdx, --force; not -n/--dry-run)
#        → destroyed = untracked files (ignored ones too with -x/-X)
#    NOT COVERED: `git checkout <file>` of one path (the caller named exactly what
#      goes; the publisher's own prose forbids it), `git reset --soft/--mixed`
#      (history/index only, nothing in the tree is lost), `git restore --staged`,
#      `git stash` (recoverable), and the segment-level limits of the header.
#
#    TARGET. The command runs in the payload's `cwd`, moved by a `cd <dir>` in an
#    earlier segment or by `git -C <dir>`. The directory must be LITERAL: a `$VAR`,
#    a substitution, `cd -`, `--git-dir`/`--work-tree`, or a path that does not
#    exist cannot be inspected, so the rule FAILS CLOSED and blocks. Every `cd` is
#    taken to persist, including one inside a subshell that would not carry over:
#    a seatbelt does not model scopes. A directory that is not a git repo has
#    nothing to lose and is allowed.
#
#    Reads `segments` with quotes dropped (`git reset "--hard"` is `--hard`), so
#    obfuscated and compound forms reach it exactly like rules 1-3. Each candidate
#    costs a `git status`, so their number is bounded and past it the verdict is
#    `block` (#511's rule: too much to inspect is denied, never waved through).
#    CEILING: `git status` over a very large tree can itself outlast the hook's
#    timeout; trigger to revisit — an audited `ms` near the limit on this rule.
# Loose on purpose: the verb only has to be a word of a `git` segment, so a
# substitution between `git` and the verb (`git -C $(pwd) reset --hard`) still
# makes the segment a candidate; the token walk below decides the real subcommand.
_dsc_re='^git[[:space:]]+(.*[[:space:]])?(reset|checkout|restore|clean)([[:space:]]|$)'
_dsc_route="commit the work first (a WIP commit is enough: 'git add -A && git commit -m wip'), or ask the user to run the discard outside the agent."
segments_dq=$(printf '%s' "$segments" | tr -d "'\")")
_dsc_cands=$(printf '%s' "$segments_dq" | grep -E "$_dsc_re" || true)
if [ -n "$_dsc_cands" ]; then
  if [ "$(printf '%s\n' "$_dsc_cands" | wc -l)" -gt 16 ]; then
    block "too many discard commands to inspect (> 16) — nothing in it was evaluated" oversize "split it into smaller commands the guard can inspect."
  fi
  # $1 dir · $2 tracked|untracked|all — succeeds when the dir holds what would be lost.
  _dsc_dirty() {
    git -C "$1" rev-parse --git-dir >/dev/null 2>&1 || return 1
    case "$2" in
      tracked) [ -n "$(GIT_OPTIONAL_LOCKS=0 git -C "$1" status --porcelain --untracked-files=no 2>/dev/null)" ] ;;
      untracked) [ -n "$(git -C "$1" ls-files --others --exclude-standard 2>/dev/null | head -n 1)" ] ;;
      *) [ -n "$(git -C "$1" ls-files --others 2>/dev/null | head -n 1)" ] ;;
    esac
  }
  # $1 base dir · $2 operand → the directory it names, or `?` when it is not literal.
  _dsc_resolve() {
    case "$2" in
      '' | '~' | '~/'*) set -- "$1" "${HOME:-?}${2#\~}" ;;
    esac
    case "$1$2" in
      *'$'* | *'`'* | *'*'* | *'?'*) printf '?' ;;
      *) case "$2" in /*) printf '%s' "$2" ;; *) printf '%s/%s' "$1" "$2" ;; esac ;;
    esac
  }
  _dsc_home=$(payload_field cwd 2>/dev/null || true)
  [ -n "$_dsc_home" ] || _dsc_home=$PWD
  _dsc_cur=$_dsc_home
  while IFS= read -r _seg; do
    case "$_seg" in
      'cd' | 'cd '*)
        _dsc_arg=${_seg#cd}
        _dsc_arg=${_dsc_arg#"${_dsc_arg%%[![:space:]]*}"}
        _dsc_arg=${_dsc_arg%"${_dsc_arg##*[![:space:]]}"}
        case "$_dsc_arg" in '-P '* | '-L '*) _dsc_arg=${_dsc_arg#-? } ;; esac
        case "$_dsc_arg" in '-' | '-'*) _dsc_cur='?' ;; *) _dsc_cur=$(_dsc_resolve "$_dsc_cur" "$_dsc_arg") ;; esac
        continue
        ;;
    esac
    printf '%s' "$_seg" | grep -qE "$_dsc_re" || continue
    _dsc_dir=$_dsc_cur
    _dsc_c=0 _dsc_sub="" _dsc_want="" _dsc_kind=""
    _dsc_hard=0 _dsc_staged=0 _dsc_wt=0 _dsc_force=0 _dsc_dry=0 _dsc_all=0 _dsc_dot=0
    while IFS= read -r _t; do
      [ -n "$_t" ] || continue
      _dsc_c=$((_dsc_c + 1))
      [ "$_dsc_c" -gt 1 ] || continue   # the `git` word itself
      if [ "$_dsc_want" = C ]; then _dsc_dir=$(_dsc_resolve "$_dsc_dir" "$_t"); _dsc_want=""; continue; fi
      if [ "$_dsc_want" = skip ]; then _dsc_want=""; continue; fi
      if [ -z "$_dsc_sub" ]; then
        case "$_t" in
          -C) _dsc_want=C ;;
          -c | --namespace) _dsc_want=skip ;;
          --git-dir | --work-tree) _dsc_dir='?'; _dsc_want=skip ;;
          --git-dir=* | --work-tree=*) _dsc_dir='?' ;;
          -*) ;;
          reset | checkout | restore | clean) _dsc_sub=$_t ;;
          *'$'* | *'`'*) _dsc_dir='?' ;;
          *) [ "$_dsc_dir" = '?' ] || _dsc_sub=$_t ;;
        esac
        continue
      fi
      case "$_t" in
        --ha | --har | --hard) _dsc_hard=1 ;;
        --staged) _dsc_staged=1 ;;
        --worktree) _dsc_wt=1 ;;
        --force) _dsc_force=1 ;;
        --dry-run) _dsc_dry=1 ;;
        --*) ;;
        -*)
          case "$_t" in *S*) _dsc_staged=1 ;; esac
          case "$_t" in *W*) _dsc_wt=1 ;; esac
          case "$_t" in *f*) _dsc_force=1 ;; esac
          case "$_t" in *n*) _dsc_dry=1 ;; esac
          case "$_t" in *x* | *X*) _dsc_all=1 ;; esac
          ;;
        . | ./ | ':/' | ':/.') _dsc_dot=1 ;;
      esac
    done <<< "$(printf '%s' "$_seg" | tr -s '[:space:]' '\n')"
    case "$_dsc_sub" in
      reset) [ "$_dsc_hard" = 1 ] && _dsc_kind=tracked ;;
      checkout) { [ "$_dsc_force" = 1 ] || [ "$_dsc_dot" = 1 ]; } && _dsc_kind=tracked ;;
      restore) { [ "$_dsc_staged" = 0 ] || [ "$_dsc_wt" = 1 ]; } && _dsc_kind=tracked ;;
      clean) { [ "$_dsc_force" = 1 ] && [ "$_dsc_dry" = 0 ]; } && { [ "$_dsc_all" = 1 ] && _dsc_kind=all || _dsc_kind=untracked; } ;;
    esac
    [ -n "$_dsc_kind" ] || continue
    _dsc_msg="git ${_dsc_sub} would discard uncommitted work"
    if [ "$_dsc_dir" = '?' ] || [ ! -d "$_dsc_dir" ]; then
      block "git ${_dsc_sub} discards work and its target directory cannot be inspected (variable, substitution, missing or unresolved path)" unspecified \
        "use a literal existing directory (cd <dir> && … or git -C <dir> …), or ${_dsc_route}"
    fi
    if _dsc_dirty "$_dsc_dir" "$_dsc_kind"; then
      block "$_dsc_msg" unspecified "$_dsc_route"
    fi
  done <<< "$segments_dq"
fi

