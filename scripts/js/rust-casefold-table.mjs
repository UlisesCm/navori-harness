import { spawn, spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * `crates/navori-hooks/src/shell/case_fold.rs`: the case-folding relation of GNU `grep -xiF` in
 * `C.UTF-8`, measured instead of derived (the `regex` crate folds differently in both directions).
 *
 *   node scripts/js/rust-casefold-table.mjs           measure and rewrite the table
 *   node scripts/js/rust-casefold-table.mjs --check   measure again; exit 1 if the table differs
 *
 * Method: every scalar value from U+0041 up to U+2FFFF whose GNU sed `\U` or `\L` differs from
 * itself is a candidate, together with those images. For each candidate pattern `p`, one
 * `/usr/bin/grep -xiF -e p` over all candidates lists the texts it matches. The relation is NOT
 * symmetric (U+1C80..U+1C88 match their base letters only as a pattern), so each pattern keeps
 * its own set. A character outside the table matches only itself.
 *
 * It reads `/usr/bin/grep` and `/usr/bin/sed` on purpose: they are the ones the shell hooks
 * resolve, and an interactive `grep` alias may be another implementation. The table is as true as
 * the host's glibc: another one fails the `--check` and the `guard_casefold` test, which is the
 * point.
 */

const HERE = fileURLToPath(new URL(".", import.meta.url));
const REPO_ROOT = resolve(HERE, "..", "..");
const TARGET = join(REPO_ROOT, "crates", "navori-hooks", "src", "shell", "case_fold.rs");
const GREP = "/usr/bin/grep";
const SED = "/usr/bin/sed";
const ENV = { PATH: "/usr/bin:/bin", LC_ALL: "C.UTF-8" };
const FIRST = 0x41;
const LAST = 0x2ffff;
const CONCURRENCY = 8;

/** @param {string} text */
const byCodePoint = (text) => text.codePointAt(0) ?? 0;

/** Every scalar value in `[FIRST, LAST]`, one per line. */
function allScalars() {
  const out = [];
  for (let cp = FIRST; cp <= LAST; cp++) {
    if (cp < 0xd800 || cp > 0xdfff) out.push(String.fromCodePoint(cp));
  }
  return out;
}

/**
 * @param {string} script
 * @param {string} input
 * @returns {string[]}
 */
function sedLines(script, input) {
  const run = spawnSync(SED, [script], {
    input,
    env: ENV,
    encoding: "utf8",
    maxBuffer: 1 << 28,
  });
  if (run.status !== 0) throw new Error(`rust-casefold-table: ${SED} failed`);
  return run.stdout.split("\n");
}

/** @returns {string[]} the candidate characters, sorted by code point */
function candidates() {
  const all = allScalars();
  const input = `${all.join("\n")}\n`;
  const upper = sedLines("s/.*/\\U&/", input);
  const lower = sedLines("s/.*/\\L&/", input);
  const found = new Set();
  all.forEach((ch, i) => {
    if (upper[i] !== ch || lower[i] !== ch) {
      found.add(ch);
      found.add(upper[i]);
      found.add(lower[i]);
    }
  });
  return [...found].sort((a, b) => byCodePoint(a) - byCodePoint(b));
}

/**
 * The texts, among `texts`, that `grep -xiF -e pattern` matches.
 *
 * @param {string} pattern
 * @param {string} texts newline-separated candidates
 * @returns {Promise<string[]>}
 */
function matches(pattern, texts) {
  return new Promise((done, fail) => {
    const child = spawn(GREP, ["-xiF", "-e", pattern], { env: ENV });
    const chunks = [];
    child.stdout.on("data", (chunk) => chunks.push(chunk));
    child.on("error", fail);
    child.on("close", (status) => {
      if (status !== 0 && status !== 1) fail(new Error(`rust-casefold-table: grep status ${status}`));
      else done(Buffer.concat(chunks).toString("utf8").split("\n").filter(Boolean));
    });
    child.stdin.on("error", () => {});
    child.stdin.end(texts);
  });
}

/** @param {string[]} chars */
async function measure(chars) {
  const texts = `${chars.join("\n")}\n`;
  const sets = new Map();
  let next = 0;
  const worker = async () => {
    while (next < chars.length) {
      const pattern = chars[next++];
      sets.set(pattern, await matches(pattern, texts));
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  return sets;
}

/** @param {string} ch */
function escape(ch) {
  return /^[A-Za-z0-9]$/.test(ch) ? ch : `\\u{${byCodePoint(ch).toString(16)}}`;
}

/**
 * @param {string[]} chars
 * @param {Map<string, string[]>} sets
 */
function render(chars, sets) {
  const rows = chars.map((ch) => {
    const set = sets.get(ch) ?? [];
    return `    ('${escape(ch)}', "${set.map(escape).join("")}"),`;
  });
  return [
    "//! GENERATED by `scripts/js/rust-casefold-table.mjs`: do not edit by hand.",
    "//!",
    "//! The case-folding relation of GNU `grep -xiF` in `C.UTF-8`, measured over every candidate",
    "//! (a scalar value whose GNU sed `\\U` or `\\L` differs from itself, and those images). Each",
    "//! entry is a PATTERN character and the text characters it matches. The relation is not",
    "//! symmetric. Sorted by pattern; a character that is not listed matches only itself.",
    "",
    `/// Pattern character and the text characters that \`grep -xiF\` matches for it (${chars.length} entries).`,
    `pub static COUNTERPARTS: [(char, &str); ${chars.length}] = [`,
    ...rows,
    "];",
    "",
  ].join("\n");
}

async function main() {
  const version = spawnSync(GREP, ["--version"], { env: ENV, encoding: "utf8" });
  if (!/GNU grep/.test(version.stdout ?? "")) {
    console.error(`rust-casefold-table: ${GREP} is not GNU grep`);
    process.exit(2);
  }
  const chars = candidates();
  const sets = await measure(chars);
  const text = render(chars, sets);
  if (process.argv.includes("--check")) {
    if (readFileSync(TARGET, "utf8") !== text) {
      console.error("rust-casefold-table: shell/case_fold.rs is stale; rerun without --check");
      process.exit(1);
    }
    console.log(`rust-casefold-table: ok (${chars.length} candidates)`);
    return;
  }
  writeFileSync(TARGET, text);
  console.log(`rust-casefold-table: wrote ${chars.length} candidates`);
}

await main();
